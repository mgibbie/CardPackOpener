// campaign.js — Campaign v1 (stage 6): hand-built maps in six chapters (Kanto's three, then Johto's three: Ilex Woods, the
// Whirl Isles and Tin Tower). Teaching maps first (move, attack, Execute, combos, height, throw and capture), then Geo
// puzzles, then height puzzles, then status, sea gaps and throwing, and the tall tower; a boss ends each chapter. A map
// opens when the one before it is cleared (the collection's `cleared`, figcol.js); its FIRST clear pays its reward: stars,
// and on some maps a figurine (its id is the map's, so two devices clearing it join into one figurine, never two).
//
// A map, as written here (overworld/tests/poketactica_campaign_test.mjs checks every one):
//   rows   heights, one string per row: '.' 0, '1'..'9' a level, '#' no tile (a gap)
//   geo    the same size: r red, b blue, p purple, o orange, c cyan, y yellow (electric), g green (grassy), . none
//   base   [x, y]: where the player's figurines are deployed from (a tile, clear of foes and symbols)
//   symbols  Geo Symbols: { x, y, color (what it repaints to; 'clear' removes colour), effect } (engine/geo.js GEO_EFFECTS)
//   foes   { sp, lv, x, y, ai ('aggro' | 'passive' | 'hold'), moves? (else the last four it learned), boss?, held? (goods.js HELD) }
//   reward { stars, fig?: { sp, lv } }   tip: what the map teaches, shown as it starts
//   theme  how it looks (terrain3d.js THEMES; else its chapter's)   ground  (optional) rows of what each tile is made of:
//          g grass, t tall grass, d dirt, s stone, a sand, n snow, i ice, w water, l lava, f wood, . the theme's own
//          (living terrain, engine/terrain.js: water / ice slow, lava burns, tall grass hides)

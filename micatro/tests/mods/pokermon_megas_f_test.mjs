// Batch F: exercise the Mega Stone and scored-card effects.
import { T, start, hand, add, play, G, P_CENTERS, act } from './poke_helpers.mjs';
import { RULES } from '../../js/mods/pins.js';

const { ok, done } = T();
start('MEGAF');
const base = add('j_poke_barbaracle');
const stone = add('c_poke_megastone');
const result = act({ type: 'use', id: stone.sort_id, joker_targets: [base.sort_id] });
G.E_MANAGER.flush();
ok(result.ok && base.config.center.key === 'j_poke_mega_barbaracle', 'Mega Stone evolves Barbaracle');
const center = P_CENTERS.j_poke_mega_barbaracle;
const [one, two] = hand(['S_7', 'H_7']);
const oneScore = center.calculate(center, base, { individual: true, cardarea: G.play, other_card: one });
ok(oneScore?.chips === 40 && oneScore?.x_mult === 1.75, 'scored 7 gives +40 Chips and X1.75', oneScore);
const repeat = (cards) => center.calculate(center, base, { repetition: true, cardarea: G.play, other_card: one, scoring_hand: cards });
ok(!repeat([one]), 'a lone 7 is not retriggered');
ok(repeat([one, two])?.repetitions === 1, 'two scored 7s retrigger each other');
const played = play([one, two]);
ok(played.res.ok && played.total && Math.abs(played.total.mult - 2 * 1.75 ** 4) < 1e-8,
  'a real pair of 7s scores each Mega effect twice', played.total);
RULES.pins = { pokermon: '3.9.1+r86' };
try { ok(!P_CENTERS.j_poke_barbaracle.megas, 'old replays do not gain a new Mega target'); } finally { RULES.pins = null; }
start('MEGAFHAWLUCHA');
const hawlucha = add('j_poke_hawlucha'), stone2 = add('c_poke_megastone');
act({ type: 'use', id: stone2.sort_id, joker_targets: [hawlucha.sort_id] });
G.E_MANAGER.flush();
ok(hawlucha.config.center.key === 'j_poke_mega_hawlucha', 'Mega Stone evolves Hawlucha');
const hc = P_CENTERS.j_poke_mega_hawlucha;
const [first, last, off] = hand(['S_2', 'S_3', 'H_4']);
const hctx = (other, scoring_hand, repetition = false) => ({ individual: !repetition, repetition, cardarea: G.play, other_card: other, scoring_hand });
ok(hc.calculate(hc, hawlucha, hctx(first, [first, last], true))?.repetitions === 2, 'first scored card retriggers twice');
ok(hc.calculate(hc, hawlucha, hctx(first, [first, last]))?.x_mult === 1.25, 'matching ends each gain X1.25');
ok(!hc.calculate(hc, hawlucha, hctx(first, [first, off])), 'different suits do not grant X Mult');
ok(hc.calculate(hc, hawlucha, hctx(first, [first], true))?.repetitions === 2, 'a lone card is retriggered twice, not four times');
start('MEGAFFALINKS');
const falinks = add('j_poke_falinks'), stone3 = add('c_poke_megastone');
act({ type: 'use', id: stone3.sort_id, joker_targets: [falinks.sort_id] }); G.E_MANAGER.flush();
ok(falinks.config.center.key === 'j_poke_mega_falinks', 'Mega Stone evolves Falinks');
const fc = P_CENTERS.j_poke_mega_falinks;
const [fa, fb, fx] = hand(['S_5', 'S_6', 'H_7']);
ok(fc.calculate(fc, falinks, { individual: true, cardarea: G.play, other_card: fa })?.mult === 12, 'each scored card gives +12 Mult');
ok(fc.calculate(fc, falinks, { joker_main: true, scoring_hand: [fa, fb] })?.Xmult_mod === 2.4, 'two suited cards give X2.4');
ok(!fc.calculate(fc, falinks, { joker_main: true, scoring_hand: [fa, fx] }), 'mixed suits do not trigger formation');
start('MEGAFEELEKTROSS');
const eel = add('j_poke_eelektross'), stone4 = add('c_poke_megastone');
act({ type: 'use', id: stone4.sort_id, joker_targets: [eel.sort_id] }); G.E_MANAGER.flush();
ok(eel.config.center.key === 'j_poke_mega_eelektross', 'Mega Stone evolves Eelektross');
const ec = P_CENTERS.j_poke_mega_eelektross;
const [steel1, steel2] = hand(['S_2', 'H_3'], { center: 'm_steel' });
ok(ec.calculate(ec, eel, { joker_main: true }).Xmult_mod === 2, 'two Steel cards give X2');
ok(ec.calculate(ec, eel, { repetition: true, cardarea: G.play, other_card: steel1, scoring_hand: [steel1, steel2] })?.repetitions === 1, 'first Steel card retriggers');
ok(!ec.calculate(ec, eel, { repetition: true, cardarea: G.play, other_card: steel2, scoring_hand: [steel1, steel2] }), 'second Steel card does not retrigger');
start('MEGAFCHANDELURE');
const ch = add('j_poke_chandelure'), stone5 = add('c_poke_megastone');
act({ type: 'use', id: stone5.sort_id, joker_targets: [ch.sort_id] }); G.E_MANAGER.flush();
ok(ch.config.center.key === 'j_poke_mega_chandelure', 'Mega Stone evolves Chandelure');
const cc = P_CENTERS.j_poke_mega_chandelure, other = add('j_joker');
other.sell_cost = 1;
ok(cc.calculate(cc, ch, { joker_main: true })?.mult_mod === ch.sell_cost * 2, 'Chandelure adds twice its sell value');
ok(cc.calculate(cc, ch, { other_joker: other })?.Xmult_mod === 1.6, '$1 Joker gives X1.6');
other.sell_cost = 2;
ok(!cc.calculate(cc, ch, { other_joker: other }), '$2 Joker does not give X1.6');
start('MEGAFSCOLIPEDE');
const scol = add('j_poke_scolipede'), stone6 = add('c_poke_megastone');
act({ type: 'use', id: stone6.sort_id, joker_targets: [scol.sort_id] }); G.E_MANAGER.flush();
ok(scol.config.center.key === 'j_poke_mega_scolipede', 'Mega Stone evolves Scolipede');
const [poisoned] = hand(['S_8']);
act({ type: 'highlight', ids: [poisoned.sort_id] });
act({ type: 'discard' }); G.E_MANAGER.flush();
ok(poisoned.ability.perma_mult === 10 && poisoned.ability.perma_bonus === -3 && poisoned.config.center.key === 'm_mult',
  'a discarded card is poisoned and becomes a Mult card', poisoned.ability);
start('MEGAFCHESNAUGHT');
const chest = add('j_poke_chesnaught'), stone7 = add('c_poke_megastone');
const size = G.hand.config.card_limit;
act({ type: 'use', id: stone7.sort_id, joker_targets: [chest.sort_id] }); G.E_MANAGER.flush();
ok(chest.config.center.key === 'j_poke_mega_chesnaught' && G.hand.config.card_limit === size, 'Mega Chesnaught retains its hand size');
const chestCenter = P_CENTERS.j_poke_mega_chesnaught;
G.GAME.current_round.hands_left = 1;
ok(chestCenter.calculate(chestCenter, chest, { joker_main: true })?.Xmult_mod === 2.5, 'two hands including current: X2.5');
const [lastChest] = hand(['S_4']);
ok(chestCenter.calculate(chestCenter, chest, { repetition: true, cardarea: G.play, scoring_hand: [lastChest], other_card: lastChest })?.repetitions === 1, 'last card retriggers with two hands including current');
G.GAME.current_round.hands_left = 0;
ok(chestCenter.calculate(chestCenter, chest, { joker_main: true })?.Xmult_mod === undefined, 'final hand has no X2.5');
start('MEGAFFROSLASS');
const frost = add('j_poke_froslass'), stone8 = add('c_poke_megastone');
act({ type: 'use', id: stone8.sort_id, joker_targets: [frost.sort_id] }); G.E_MANAGER.flush();
ok(frost.config.center.key === 'j_poke_mega_froslass' && G.GAME.bankrupt_at === -30, 'Mega Froslass allows $30 debt');
const frostCenter = P_CENTERS.j_poke_mega_froslass;
G.GAME.dollars = -1;
ok(frostCenter.calculate(frostCenter, frost, { joker_main: true })?.Xmult_mod === 2, 'shallow debt gives X2');
G.GAME.dollars = -15;
ok(frostCenter.calculate(frostCenter, frost, { joker_main: true })?.Xmult_mod === 3, 'deep debt gives X3 instead');
G.GAME.dollars = 0;
ok(!frostCenter.calculate(frostCenter, frost, { joker_main: true }), 'no debt gives no multiplier or Item');
start('MEGAFFLOETTE');
const floette = add('j_poke_floette'), stone9 = add('c_poke_megastone');
floette.ability.extra.rounds = 2; const flower = floette.ability.extra.form;
act({ type: 'use', id: stone9.sort_id, joker_targets: [floette.sort_id] }); G.E_MANAGER.flush();
ok(floette.config.center.key === 'j_poke_mega_floette', 'Mega Stone evolves Floette');
const floetteCenter = P_CENTERS.j_poke_mega_floette;
const [q1, q2] = hand(['S_Q', 'H_Q']);
ok(floetteCenter.calculate(floetteCenter, floette, { repetition: true, cardarea: G.play, other_card: q1 })?.repetitions === 2, 'Queen retriggers twice');
ok(floetteCenter.calculate(floetteCenter, floette, { individual: true, cardarea: G.play, other_card: q1 })?.x_mult === 1.5, 'Queen gives X1.5');
ok(floetteCenter.calculate(floetteCenter, floette, { joker_main: true, scoring_hand: [q1, q2] })?.dollars === 3, 'two Queens pay $3');
stone9.ability.extra.usable = true;
act({ type: 'use', id: stone9.sort_id, joker_targets: [floette.sort_id] }); G.E_MANAGER.flush();
ok(floette.config.center.key === 'j_poke_floette' && floette.ability.extra.rounds === 2 && floette.ability.extra.form === flower, 'reverting Floette preserves its evolution timer and flower');
start('MEGAFEMBOAR');
const emboar = add('j_poke_emboar'), stone10 = add('c_poke_megastone');
act({ type: 'use', id: stone10.sort_id, joker_targets: [emboar.sort_id] }); G.E_MANAGER.flush();
ok(emboar.config.center.key === 'j_poke_mega_emboar', 'Mega Stone evolves Emboar');
const emboarCenter = P_CENTERS.j_poke_mega_emboar;
for (let i = 0; i < 3; i++) emboarCenter.calculate(emboarCenter, emboar, { before: true, cardarea: G.jokers, scoring_name: 'Pair' });
ok(emboarCenter.calculate(emboarCenter, emboar, { joker_main: true })?.Xmult_mod === 2.5, 'three consecutive hands give X2.5');
const [emCard] = hand(['S_9']);
ok(emboarCenter.calculate(emboarCenter, emboar, { repetition: true, cardarea: G.play, scoring_hand: [emCard], other_card: emCard })?.repetitions === 1, 'three consecutive hands retrigger first scored card');
start('MEGAFEXCADRILL');
const drill = add('j_poke_excadrill'), stone11 = add('c_poke_megastone');
act({ type: 'use', id: stone11.sort_id, joker_targets: [drill.sort_id] }); G.E_MANAGER.flush();
ok(drill.config.center.key === 'j_poke_mega_excadrill', 'Mega Stone evolves Excadrill');
const drillCenter = P_CENTERS.j_poke_mega_excadrill;
G.playing_cards.pop(); G.playing_cards.pop();
ok(drillCenter.calculate(drillCenter, drill, { joker_main: true, scoring_hand: [] })?.mult_mod === 8, 'two cards below 52 give +8 Mult');
const [rock] = hand(['S_6'], { center: 'm_stone' });
ok(drillCenter.calculate(drillCenter, drill, { destroying_card: rock }) === true, 'played Stone is destroyed for treasure');
start('MEGAFDELPHOX');
const delphox = add('j_poke_delphox'); delphox.ability.extra.fire_Xmult = 2.2;
const stone12 = add('c_poke_megastone');
act({ type: 'use', id: stone12.sort_id, joker_targets: [delphox.sort_id] }); G.E_MANAGER.flush();
ok(delphox.config.center.key === 'j_poke_mega_delphox' && delphox.ability.extra.fire_Xmult === 2.2, 'Mega Delphox keeps its bank');
const dc = P_CENTERS.j_poke_mega_delphox;
const tarot = add('c_fool');
G.consumeables.config.card_limit += 2;
dc.calculate(dc, delphox, { using_consumeable: true, consumeable: tarot }); G.E_MANAGER.flush();
ok(delphox.ability.extra.fire_Xmult === 2.6 && G.consumeables.cards.some((c) => c.ability.set === 'Planet'), 'Tarot banks X0.4 and creates a Planet');
start('MEGAFDRAGALGE');
const drag = add('j_poke_dragalge'), stone13 = add('c_poke_megastone');
act({ type: 'use', id: stone13.sort_id, joker_targets: [drag.sort_id] }); G.E_MANAGER.flush();
ok(drag.config.center.key === 'j_poke_mega_dragalge', 'Mega Stone evolves Dragalge');
const dragCenter = P_CENTERS.j_poke_mega_dragalge;
dragCenter.calculate(dragCenter, drag, { setting_blind: true }); G.E_MANAGER.flush();
ok(G.playing_cards.filter((c) => c.config.center.key === 'm_poke_hazard').length === 2, 'blind selection creates two Hazards');
const [haz] = hand(['S_2'], { center: 'm_poke_hazard' });
ok(dragCenter.calculate(dragCenter, drag, { individual: true, cardarea: G.hand, other_card: haz })?.x_mult === 1.5, 'held Hazard gives X1.5');
start('MEGAFSCRAFTY');
const scrafty = add('j_poke_scrafty'); scrafty.ability.extra.mult = 23;
const stone14 = add('c_poke_megastone');
act({ type: 'use', id: stone14.sort_id, joker_targets: [scrafty.sort_id] }); G.E_MANAGER.flush();
ok(scrafty.config.center.key === 'j_poke_mega_scrafty' && scrafty.ability.extra.mult === 23, 'Mega Scrafty preserves Moxie');
const sc = P_CENTERS.j_poke_mega_scrafty;
G.GAME.current_round.hands_played = 0;
ok(sc.calculate(sc, scrafty, { joker_main: true })?.Xmult_mod === 2.5, 'first hand gives X2.5');
G.GAME.current_round.hands_played = 1;
sc.calculate(sc, scrafty, { end_of_round: true, cardarea: G.jokers }); G.E_MANAGER.flush();
ok(scrafty.ability.extra.mult === 29, 'first-hand win grants double Moxie');
start('MEGAFMALAMAR');
const malamar = add('j_poke_malamar'), stone15 = add('c_poke_megastone');
act({ type: 'use', id: stone15.sort_id, joker_targets: [malamar.sort_id] }); G.E_MANAGER.flush();
ok(malamar.config.center.key === 'j_poke_mega_malamar', 'Mega Stone evolves Malamar');
const mc = P_CENTERS.j_poke_mega_malamar;
const [lowTwo, lowFive] = hand(['S_2', 'H_5']);
ok(lowTwo.get_chip_bonus() === 11, 'Mega Malamar preserves flipped rank Chips');
ok(mc.calculate(mc, malamar, { individual: true, cardarea: G.play, other_card: lowTwo })?.x_mult === 1.5, 'scored 2 gives X1.5');
ok(mc.calculate(mc, malamar, { repetition: true, cardarea: G.play, other_card: lowTwo, scoring_hand: [lowTwo, lowFive] })?.repetitions === 1, '2 and 5 retrigger one another');
start('MEGAFPYROAR');
const pyroar = add('j_poke_pyroar'), stone16 = add('c_poke_megastone');
act({ type: 'use', id: stone16.sort_id, joker_targets: [pyroar.sort_id] }); G.E_MANAGER.flush();
ok(pyroar.config.center.key === 'j_poke_mega_pyroar', 'Mega Stone evolves Pyroar');
const pc = P_CENTERS.j_poke_mega_pyroar, [pk, pq] = hand(['S_K', 'S_Q']);
const pr = pc.calculate(pc, pyroar, { joker_main: true, poker_hands: { Flush: [true] }, scoring_hand: [pk, pq] }); G.E_MANAGER.flush();
ok(pr?.chip_mod === 180 && pr?.Xmult_mod === 3, 'Flush with King and Queen gives +180 Chips and X3');
ok(G.consumeables.cards.some((c) => c.ability.set === 'Energy'), 'royal Flush creates Energy when there is room');
start('MEGAFZYGARDE');
const zy = add('j_poke_zygarde'), stone17 = add('c_poke_megastone');
ok(!act({ type: 'use', id: stone17.sort_id, joker_targets: [zy.sort_id] }).ok, 'Zygarde cannot Mega Evolve before Complete Forme');
zy.ability.extra.cells = 100;
P_CENTERS.j_poke_zygarde.add_to_deck(P_CENTERS.j_poke_zygarde, zy); G.E_MANAGER.flush();
const zySize = G.hand.config.card_limit;
act({ type: 'use', id: stone17.sort_id, joker_targets: [zy.sort_id] }); G.E_MANAGER.flush();
ok(zy.config.center.key === 'j_poke_mega_zygarde' && G.hand.config.card_limit === zySize, 'Complete Zygarde becomes Mega with one hand-size bonus');
stone17.ability.extra.usable = true;
act({ type: 'use', id: stone17.sort_id, joker_targets: [zy.sort_id] }); G.E_MANAGER.flush();
ok(zy.config.center.key === 'j_poke_zygarde' && zy.ability.extra.cells === 100 && G.hand.config.card_limit === zySize, 'reverting preserves Cells and one hand-size bonus');
start('MEGAFGRENINJA');
const ninja = add('j_poke_greninja'), partner = add('j_poke_squirtle'), stone18 = add('c_poke_megastone');
act({ type: 'use', id: stone18.sort_id, joker_targets: [ninja.sort_id] }); G.E_MANAGER.flush();
ok(ninja.config.center.key === 'j_poke_mega_greninja', 'Mega Stone evolves Greninja');
const nc = P_CENTERS.j_poke_mega_greninja;
ok(nc.calculate(nc, ninja, { joker_main: true })?.Xmult_mod === 3, 'one matching Water Joker gives X3');
const [ncard] = hand(['S_3']);
ok(nc.calculate(nc, ninja, { repetition: true, cardarea: G.play, scoring_hand: [ncard], other_card: ncard })?.repetitions === 1, 'one matching Joker retriggers the first card');
for (const name of ['froslass', 'emboar', 'excadrill', 'scolipede', 'scrafty', 'eelektross', 'chandelure', 'chesnaught', 'delphox', 'greninja', 'pyroar', 'floette', 'malamar', 'barbaracle', 'dragalge', 'hawlucha', 'zygarde', 'falinks']) {
  start('FROUNDTRIP' + name);
  const j = add('j_poke_' + name), st = add('c_poke_megastone');
  if (name === 'zygarde') { j.ability.extra.cells = 100; P_CENTERS.j_poke_zygarde.add_to_deck(P_CENTERS.j_poke_zygarde, j); G.E_MANAGER.flush(); }
  const beforeSize = G.hand.config.card_limit;
  const result = act({ type: 'use', id: st.sort_id, joker_targets: [j.sort_id] }); G.E_MANAGER.flush();
  ok(result.ok && j.config.center.key === 'j_poke_mega_' + name && st.ability.extra.used_on === j.unique_val, name + ': Mega Stone links the Mega');
  st.ability.extra.usable = true;
  const back = act({ type: 'use', id: st.sort_id, joker_targets: [j.sort_id] }); G.E_MANAGER.flush();
  ok(back.ok && j.config.center.key === 'j_poke_' + name && st.ability.extra.used_on === undefined && G.hand.config.card_limit === beforeSize, name + ': reverting restores the base and hand size');
}
done();

// Mega Dimension: Glimmora's Mega Stone target and held-Hazard scoring.
import { T, start, hand, add, act, G, P_CENTERS } from './poke_helpers.mjs';
import { RULES } from '../../js/mods/pins.js';
const { ok, done } = T();
for (const n of ['staraptor', 'glimmora', 'tatsugiri', 'chimecho', 'meowstic', 'crabominable', 'scovillain']) {
  start('MD' + n);
  const base = P_CENTERS['j_poke_' + n], mega = P_CENTERS['j_poke_mega_' + n];
  ok(base.megas?.includes('mega_' + n) && mega?.stage === 'Mega' && mega.soul_pos, `${n}: correct Mega Stone target and floating art`);
  RULES.pins = { pokermon: '3.9.1+r107' };
  try { ok(!base.megas?.includes('mega_' + n), `${n}: unavailable in old r107 replays`); } finally { RULES.pins = null; }
}
start('MDGLIM');
const gl = add('j_poke_glimmora'), stone = add('c_poke_megastone');
act({ type: 'use', id: stone.sort_id, joker_targets: [gl.sort_id] }); G.E_MANAGER.flush();
ok(gl.config.center.key === 'j_poke_mega_glimmora', 'Glimmora Mega Evolves using the Mega Stone', gl.config.center.key);
ok(gl.ability.extra.debris_cap === 4 && gl.ability.extra.Xmult_multi === 1.35, 'Mega Glimmora has the approved cap and multiplier', gl.ability.extra);
const hazard = hand(['S_2'], { center: 'm_poke_hazard' })[0];
const effect = gl.config.center.calculate(gl.config.center, gl, { individual: true, cardarea: G.hand, other_card: hazard });
ok(effect && (effect.x_mult === 1.35 || effect.Xmult_mod === 1.35), 'a held Hazard gives X1.35', effect);
const before = G.playing_cards.filter(c => c.config.center.key === 'm_poke_hazard').length;
const stones = hand(['S_3', 'S_4', 'S_5', 'S_6', 'S_7'], { center: 'm_stone' });
for (const c of stones) gl.config.center.calculate(gl.config.center, gl, { individual: true, cardarea: G.play, other_card: c });
G.E_MANAGER.flush();
const after = G.playing_cards.filter(c => c.config.center.key === 'm_poke_hazard').length;
ok(after === before + 4, 'five scored Stones convert at most four deck cards to Hazards', [before, after]);
ok(P_CENTERS.j_poke_mega_glimmora?.gen === 9, 'Mega Glimmora is Gen 9');
start('MDCRAB');
const crab = add('j_poke_crabominable'), cs = add('c_poke_megastone');
act({ type: 'use', id: cs.sort_id, joker_targets: [crab.sort_id] }); G.E_MANAGER.flush();
const [face, other] = hand(['S_K', 'H_2']);
const cc = crab.config.center, beforeMoney = G.GAME.dollars;
for (const c of [face, face, other, other]) cc.calculate(cc, crab, { individual: true, cardarea: G.play, other_card: c, scoring_hand: [face, other] });
G.E_MANAGER.flush();
ok(face.ability.perma_mult === 6 && other.ability.perma_mult === 2, 'Mega Crabominable gives its permanent Mult once per card even on retriggers');
ok(G.GAME.dollars === beforeMoney + 3, 'Mega Crabominable pays $3 for a face card first');
start('MDSCOV');
const scov = add('j_poke_scovillain'), ss = add('c_poke_megastone');
act({ type: 'use', id: ss.sort_id, joker_targets: [scov.sort_id] }); G.E_MANAGER.flush();
const [heart, club] = hand(['H_2', 'C_3']), s = scov.config.center;
const scoring = s.calculate(s, scov, { individual: true, cardarea: G.play, other_card: heart, scoring_hand: [heart, club] });
const repeat = s.calculate(s, scov, { repetition: true, cardarea: G.play, other_card: heart, scoring_hand: [heart, club] });
ok(scoring?.chips === 40 && scoring?.x_mult === 1.5 && repeat?.repetitions === 1, 'Mega Scovillain scores and retriggers Hearts with a Club');
ok(!s.calculate(s, scov, { repetition: true, cardarea: G.play, other_card: heart, scoring_hand: [heart] }), 'Mega Scovillain requires both suits to retrigger');
start('MDCHIME');
const chime = add('j_poke_chimecho'), st = add('c_poke_megastone');
act({ type: 'use', id: st.sort_id, joker_targets: [chime.sort_id] }); G.E_MANAGER.flush();
const broken = hand(['S_2', 'S_3', 'S_4', 'S_5', 'S_6'], { center: 'm_glass' });
const count = G.playing_cards.length, center = chime.config.center;
center.calculate(center, chime, { remove_playing_cards: true, removed: broken }); G.E_MANAGER.flush();
const copies = G.playing_cards.slice(count);
ok(chime.config.center.key === 'j_poke_mega_chimecho' && copies.length === 4 && copies.every(c => c.ability.perma_bonus === 10), 'Mega Chimecho restores at most four Glass cards with +10 Chips');
ok(chime.ability.extra.glass_restored === 4, 'Mega Chimecho tracks its round cap');
start('MDSTAR');
const bird = add('j_poke_staraptor'), bs = add('c_poke_megastone');
act({ type: 'use', id: bs.sort_id, joker_targets: [bird.sort_id] }); G.E_MANAGER.flush();
const bc = bird.config.center;
ok(bc.calculate(bc, bird, { joker_main: true })?.Xmult_mod === 1, 'Fighting Mega Staraptor gives X1 without Colorless Jokers');
add('j_poke_starly');
ok(bc.calculate(bc, bird, { joker_main: true })?.Xmult_mod === 1.75, 'Mega Staraptor gives X1.75 with one Colorless Joker');
const cash = G.GAME.dollars;
G.GAME.chips = G.GAME.blind.chips;
bc.calculate(bc, bird, { after: true, cardarea: G.jokers }); G.E_MANAGER.flush();
ok(G.GAME.dollars === cash + 3, 'Mega Staraptor refunds $3 when the Blind is beaten');
start('MDTATSU');
const tatsu = add('j_poke_tatsugiri'); tatsu.ability.extra.form = 'droopy';
const dozo = add('j_poke_dondozo'), ts = add('c_poke_megastone');
act({ type: 'use', id: ts.sort_id, joker_targets: [tatsu.sort_id] }); G.E_MANAGER.flush();
const tc = tatsu.config.center;
ok(tc.key === 'j_poke_mega_tatsugiri' && tatsu.ability.extra.form === 'droopy', 'Mega Tatsugiri preserves its rolled form');
ok(tc.calculate(tc, tatsu, { other_joker: dozo })?.chip_mod === 180, 'Droopy Mega Tatsugiri gives its commanded Dondozo +180 Chips');
ok(tc.calculate(tc, tatsu, { retrigger_joker_check: true, other_card: dozo })?.repetitions === 1, 'Mega Tatsugiri retriggers commanded Dondozo');
start('MDMEOW');
const meow = add('j_poke_meowstic'); meow.ability.extra.form = 'male';
const ms = add('c_poke_megastone'); act({ type: 'use', id: ms.sort_id, joker_targets: [meow.sort_id] }); G.E_MANAGER.flush();
const mc = meow.config.center;
ok(mc.key === 'j_poke_mega_meowstic' && meow.ability.extra.form === 'male', 'Mega Meowstic keeps its gender');
mc.calculate(mc, meow, { using_consumeable: true, consumeable: { ability: { set: 'Tarot' } } });
ok(meow.ability.extra.male_Xmult === 1.15 && mc.calculate(mc, meow, { joker_main: true }).Xmult_mod === 1.15, 'male Mega Meowstic banks X0.15 for a Tarot');
meow.ability.extra.form = 'female';
ok(mc.calculate(mc, meow, { joker_main: true }).Xmult_mod === 2, 'female Mega Meowstic gives X2 without Tarots');
mc.calculate(mc, meow, { using_consumeable: true, consumeable: { ability: { set: 'Tarot' } } }); G.E_MANAGER.flush();
const tarots = () => G.consumeables.cards.filter(c => c.ability.set === 'Tarot').length;
ok(tarots() === 1, 'female Mega Meowstic replaces the first Tarot');
mc.calculate(mc, meow, { using_consumeable: true, consumeable: { ability: { set: 'Tarot' } } }); G.E_MANAGER.flush();
ok(tarots() === 1, 'female Mega Meowstic replaces no more than one Tarot per round');
start('MDMEOWREAL');
const realMeow = add('j_poke_meowstic'); realMeow.ability.extra.form = 'female';
const realStone = add('c_poke_megastone'); act({ type: 'use', id: realStone.sort_id, joker_targets: [realMeow.sort_id] }); G.E_MANAGER.flush();
const tarot = add('c_hermit');
const used = act({ type: 'use', id: tarot.sort_id }); G.E_MANAGER.flush();
ok(used.ok && G.consumeables.cards.filter(c => c.ability.set === 'Tarot').length === 1, 'female Mega Meowstic replaces a Tarot used from a full consumable row');
done();

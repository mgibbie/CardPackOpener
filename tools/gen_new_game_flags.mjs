// gen_new_game_flags.mjs — the hide flags FireRed and Emerald SET on a new game.
//
// Both games start a save with InitEventData (every flag clear) and then run
// EventScript_ResetAllMapFlags from NewGameInitData (src/new_game.c), which
// setflags a list of FLAG_HIDE_* — the credits cast standing on Indigo Plateau's
// door, the rival waiting on Route 22, Birch on Route 110, the Seafloor Cavern
// villains... This port never ran that script, so on every FRLG/Emerald save those
// objects stood in the world from day one. On 2026-10-10 the credits-only OAK and
// rival sat on the League's only door (FLAG_HIDE_CREDITS_*), sealing the Elite
// Four from an 8-badge save.
//
// Two lists per region, extracted verbatim:
//   all          every flag the script sets — what a NEW game starts with
//   neverCleared the ones no script/C code in that decomp ever clears. Those
//                objects only ever appear through a scripted `addobject`, so
//                setting the flag can never hide something a player has earned.
//                The port applies ONLY these (seedNewGameFlags), to every save:
//                the others are cleared by opening/story scenes the free-roam
//                port skips (Oak's lab, Birch's lab), so setting them would hide
//                those NPCs for good.
//
//   node tools/gen_new_game_flags.mjs           (report)
//   node tools/gen_new_game_flags.mjs --write   (write overworld/new_game_flags.js)
import fs from 'fs';
import path from 'path';

const WRITE = process.argv.includes('--write');
const REF = path.resolve('../Magepunk66/Reference');
const SRC = {
	KANTO: { root: 'pokefirered', file: 'data/event_scripts.s' },
	HOENN: { root: 'pokeemerald', file: 'data/scripts/new_game.inc' },
};

// every .s/.inc/.pory under data/ and .c/.h under src/, read once per decomp
function corpus(root) {
	const out = [];
	const walk = d => {
		for (const e of fs.readdirSync(d, { withFileTypes: true })) {
			const p = path.join(d, e.name);
			if (e.isDirectory()) walk(p);
			else if (/\.(s|inc|pory|c|h)$/.test(e.name)) out.push(fs.readFileSync(p, 'utf8'));
		}
	};
	walk(path.join(REF, root, 'data'));
	walk(path.join(REF, root, 'src'));
	return out.join('\n');
}

const result = {};
for (const [region, { root, file }] of Object.entries(SRC)) {
	const src = fs.readFileSync(path.join(REF, root, file), 'utf8');
	const m = /^EventScript_ResetAllMapFlags::\r?\n([\s\S]*?)^\s*end\s*$/m.exec(src);
	if (!m) { console.error(`${root}: EventScript_ResetAllMapFlags not found`); process.exit(1); }
	const all = [];
	for (const line of m[1].split('\n')) {
		const f = /^\s*setflag\s+([A-Z0-9_]+)/.exec(line);
		if (f && !all.includes(f[1])) all.push(f[1]);
	}
	const text = corpus(root);
	const cleared = f => new RegExp(`clearflag\\s+${f}\\b|FlagClear\\(\\s*${f}\\s*\\)`).test(text);
	const neverCleared = all.filter(f => !cleared(f));
	result[region] = { all, neverCleared };
	console.log(`${region} (${root}): ResetAllMapFlags sets ${all.length}; never cleared anywhere: ${neverCleared.length}`);
}

if (WRITE) {
	const body = `// new_game_flags.js — GENERATED by tools/gen_new_game_flags.mjs. Do not edit.
//
// The FLAG_HIDE_* list each GBA decomp's EventScript_ResetAllMapFlags sets on a
// new game (all), and the subset no script ever clears (neverCleared: safe to
// reconcile onto existing saves). See the generator for why.
export const NEW_GAME_FLAGS = ${JSON.stringify(result, null, '\t')};
`;
	fs.writeFileSync(path.resolve('overworld/new_game_flags.js'), body.replace(/\r?\n/g, '\n'));
	console.log('wrote overworld/new_game_flags.js');
}

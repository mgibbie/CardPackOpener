// gen_audio_index.mjs — what the owner's /audioswap/ page lists: every track and sound each game has, read from the
// games' own files. Writes audioswap/audio_index.json (committed; audioswap_test fails when it is out of date).
//   node tools/gen_audio_index.mjs            write it
//   node tools/gen_audio_index.mjs --check    exit 1 if the committed file differs
// (the overworld's per-map music and its battle themes are not here: the page reads data/music_map.json and
//  overworld/bgm_themes.js itself)
import fs from 'fs';
import path from 'path';
import vm from 'vm';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const uniq = (a) => [...new Set(a)].sort();

// overworld: the files (the offload project's manifest), and the effect names the code plays
const manifest = rd('tools/cloud/owdata_manifest.txt').split(/\r?\n/);
const files = (dir) => uniq(manifest.map((l) => new RegExp('^sounds/' + dir + '/([^/]+)\\.ogg$').exec(l.trim())).filter(Boolean).map((m) => m[1]));
const extra = [...rd('overworld/sound.js').matchAll(/^\t'((?:crystal|firered|emerald)_[A-Z0-9_]+)'/gm)].map((m) => m[1]);
const owFiles = fs.readdirSync(path.join(ROOT, 'overworld')).filter((f) => f.endsWith('.js'));
const sfxUsed = uniq(owFiles.flatMap((f) => [...rd('overworld/' + f).matchAll(/\bsfx\('([a-z0-9_]+)'\)/g)].map((m) => m[1])));
const sfxFiles = files('sfx');

// Micatro (and Scoundrel, Pair of Pears): the base sound set
const known = /const KNOWN = new Set\(\[([\s\S]*?)\]\)/.exec(rd('micatro/js/ui/sound.js'));
const mtSounds = uniq([...known[1].matchAll(/'([^']+)'/g)].map((m) => m[1]));

// MicaSurvivor: its songs (data) and effects (recipes)
const G = {}; vm.runInNewContext(rd('micasurvivor/js/data/music.js'), { G, window: { G } });
const block = (src, open, close) => { const a = src.indexOf(open); if (a < 0) throw new Error('no ' + open); const b = src.indexOf(close, a); return src.slice(a + open.length, b); };
const msSfx = uniq([...block(rd('micasurvivor/js/core/audio.js'), 'const SFX = {', '\n  };').matchAll(/^ {4}(\w+):/gm)].map((m) => m[1]));

// Battlecards: its effects (recipes)
const bcSfx = uniq([...block(rd('battlecards/sfx.js'), 'const LIB = {', '\n};').matchAll(/^\t(\w+):/gm)].map((m) => m[1]));

const out = {
	note: 'generated by tools/gen_audio_index.mjs — do not edit',
	ow: { bgm: uniq([...files('bgm'), ...extra]), extra: uniq(extra), sfx: sfxFiles, sfxUsed: sfxUsed.filter((n) => sfxFiles.includes(n)), sfxSilent: sfxUsed.filter((n) => !sfxFiles.includes(n)) },
	mt: { sounds: mtSounds, music: ['base', 'pears_meadows'] },
	ms: { music: Object.keys(G.MUSIC || {}).sort(), sfx: msSfx },
	bc: { sfx: bcSfx },
};
const text = JSON.stringify(out, null, '\t') + '\n', file = path.join(ROOT, 'audioswap/audio_index.json');
if (process.argv.includes('--check')) {
	const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
	if (have !== text) { console.error('audioswap/audio_index.json is out of date: node tools/gen_audio_index.mjs'); process.exit(1); }
	console.log('audio index up to date');
} else {
	fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text);
	console.log(`audio index: overworld ${out.ow.bgm.length} tracks, ${out.ow.sfx.length} effects (${out.ow.sfxUsed.length} used, ${out.ow.sfxSilent.length} named with no file); Micatro ${out.mt.sounds.length}; MicaSurvivor ${out.ms.music.length} songs, ${out.ms.sfx.length} effects; Battlecards ${out.bc.sfx.length}`);
}

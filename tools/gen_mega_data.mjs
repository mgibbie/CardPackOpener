// gen_mega_data.mjs — every Mega Evolution and Primal Reversion as a BATTLE FORM
// for the overworld RPG, from the Pokemon Showdown data in the owner's Reference
// folder (data/pokedex.ts + data/items.ts). Writes overworld/mega_data.js.
//
// Megas are deliberately NOT species: they never enter species_battle.json, so
// the Pokedex, the species-coverage count, the design wiki and the RIFT PRISM's
// form cycle (ow_scaling.js formsOf) never see them. battle.js reads them from
// this module only while a battle is on, and the form reverts when it ends.
//
// WAVE 1 = the 48 X/Y + ORAS Megas and the two Primals (art in
// overworld/mega_sprites/, from the Essentials packs: tools/gen_mega_wave1_art.py).
// WAVE 2 = the Legends Z-A / Mega Dimension Megas (art in overworld/data/pokemon from
// tools/gen_mega_sprites.py), behind MEGA_WAVE2_ENABLED in overworld/mega.js.
//
//   node tools/gen_mega_data.mjs [--ref <showdown data dir>]
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const REF = args.includes('--ref') ? args[args.indexOf('--ref') + 1]
	: (process.env.SHOWDOWN_DATA || 'C:/Users/guide/Desktop/Magepunk66/Reference/pokemon-showdown-master/data');
const load = f => new Function(fs.readFileSync(path.join(REF, f), 'utf8').replace(/^export const \w+:[^=]+=/m, 'return '))();
const dex = load('pokedex.ts');
// items.ts carries TypeScript in its handlers: only the names are needed
const items = {};
for (const m of fs.readFileSync(path.join(REF, 'items.ts'), 'utf8').matchAll(/^\t(\w+): \{\r?\n\t\tname: "([^"]+)"/gm)) items[m[1]] = { name: m[2] };
const norm = s => String(s).toLowerCase().replace(/[^a-z0-9]/g, '');

// the 48 X/Y + ORAS Mega bases, and the two Primals
const WAVE1 = new Set(('venusaur charizard blastoise alakazam gengar kangaskhan pinsir gyarados aerodactyl mewtwo ampharos scizor '
	+ 'heracross houndoom tyranitar blaziken gardevoir mawile aggron medicham manectric banette absol garchomp lucario abomasnow '
	+ 'beedrill pidgeot slowbro steelix sceptile swampert sableye sharpedo camerupt altaria glalie salamence metagross latias '
	+ 'latios rayquaza lopunny gallade audino diancie kyogre groudon').split(' '));

// the wave-2 battle sprites (PR #960): Showdown name -> s<n>.png in overworld/data/pokemon
const W2ART = Object.fromEntries(JSON.parse(fs.readFileSync(path.join(ROOT, 'tools/data/mega_sprites.json'), 'utf8')).megas.map(m => [m.name, m.sprite]));
const forms = {}, stones = {}, orbs = {};
for (const [sid, e] of Object.entries(dex)) {
	if (!/(Mega|Primal)/.test(e.forme || '') || !(e.num > 0) || e.isNonstandard === 'CAP') continue;
	const base = norm(e.baseSpecies);
	const id = base + '_' + e.forme.toLowerCase().replace(/-/g, '_');
	// Z-A gives a few old Megas a second form (Absol-Mega-Z, Garchomp-Mega-Z, Lucario-Mega-Z)
	const wave = WAVE1.has(base) && !/-Z$/.test(e.forme) ? 1 : 2;
	const primal = e.forme === 'Primal';
	// a cosmetic variant whose base form the overworld has no entry for
	const variant = /^(F|Original|Droopy|Stretchy)-Mega$/.test(e.forme) ? e.forme.split('-')[0].toLowerCase() : undefined;
	const req = e.requiredItem || null;
	const f = {
		name: e.name, base, num: e.num, forme: e.forme, wave,
		types: [...e.types],
		baseStats: { ...e.baseStats },
		ability: norm(e.abilities[0]), abilityName: e.abilities[0],
		// wave 1: the Essentials-pack art in overworld/mega_sprites (tools/gen_mega_wave1_art.py);
		// wave 2: overworld/data/pokemon, numbered by tools/gen_mega_sprites.py (tools/data/mega_sprites.json)
		sprite: wave === 1 ? `mega_sprites/${id}.png` : `data/pokemon/${W2ART[e.name]}`,
		weightkg: e.weightkg,
	};
	if (primal) { f.primal = true; f.orb = norm(req); }
	else if (e.requiredMove) f.move = norm(e.requiredMove);   // Rayquaza: knows Dragon Ascent, no stone
	else f.stone = norm(req);
	if (variant) f.variant = variant;
	forms[id] = f;
	if (f.stone) {
		const it = items[f.stone];
		if (!it) throw new Error('no item ' + f.stone);
		const st = stones[f.stone] ||= { name: it.name.toUpperCase(), forms: {}, wave };
		st.forms[variant ? base + '_' + variant : base] = id;
		st.wave = Math.min(st.wave, wave);
	}
	if (f.orb) orbs[f.orb] = { name: items[f.orb].name.toUpperCase(), species: base, form: id };
}
const ids = Object.keys(forms);
const w1 = ids.filter(i => forms[i].wave === 1);
if (Object.values(forms).some(f => /undefined/.test(f.sprite))) throw new Error('a wave-2 form has no sprite in tools/data/mega_sprites.json');
if (ids.length !== 99 || w1.length !== 50) throw new Error(`expected 99 forms / 50 wave-1, got ${ids.length} / ${w1.length}`);

const out = `// mega_data.js — GENERATED by tools/gen_mega_data.mjs from Pokemon Showdown's
// data/pokedex.ts + data/items.ts. Do not edit by hand; re-run the tool.
//
// ${ids.length} Mega Evolutions + Primal Reversions as BATTLE FORMS (never species: they are kept
// out of species_battle.json, the Pokedex, the coverage count and the RIFT PRISM).
// wave 1 = X/Y + ORAS + the Primals (${w1.length}); wave 2 = Legends Z-A / Mega Dimension
// (${ids.length - w1.length}); overworld/mega.js MEGA_WAVE2_ENABLED switches wave 2.
export const MEGA_FORMS = ${JSON.stringify(forms, null, 0).replace(/\},"/g, '},\n"')};

// held MEGA STONES: item id -> { name, forms: { base species id: mega form id }, wave }
export const MEGA_STONES = ${JSON.stringify(stones, null, 0).replace(/\},"/g, '},\n"')};

// the Primal ORBS: item id -> { name, species, form }
export const PRIMAL_ORBS = ${JSON.stringify(orbs)};
`;
fs.writeFileSync(path.join(ROOT, 'overworld/mega_data.js'), out);
console.log(`mega_data.js: ${ids.length} forms (${w1.length} wave 1), ${Object.keys(stones).length} stones (${Object.values(stones).filter(s => s.wave === 1).length} wave 1), ${Object.keys(orbs).length} orbs`);

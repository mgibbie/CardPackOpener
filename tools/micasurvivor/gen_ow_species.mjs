// tools/micasurvivor/gen_ow_species.mjs — the overworld's species ids -> national dex (1..1025), for MicaSurvivor's
// unified unlocks (owner 2026-11-02: "catching a pokemon in the overworld ... should unlock it in MicaSurvivor").
// Reads overworld/data/species_index.json ({id: {name, num, sprite}}; num <= 0 = fakemon / custom: skipped) and writes
// micasurvivor/js/data/ow-species.js: G.OW_SPECIES = {id: dex}. A regional / alternate form maps to its species' number.
//   node tools/micasurvivor/gen_ow_species.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../');
const idx = JSON.parse(fs.readFileSync(path.join(ROOT, 'overworld/data/species_index.json'), 'utf8'));
const out = {};
for (const [id, v] of Object.entries(idx)) { const n = v && v.num | 0; if (n >= 1 && n <= 1025) out[id] = n; }
const dexes = new Set(Object.values(out));
const body = '/* micasurvivor/js/data/ow-species.js — GENERATED by tools/micasurvivor/gen_ow_species.mjs from overworld/data/species_index.json.\n'
  + ' * The overworld game\'s species ids -> the national dex number (1..1025): its caught Pokémon unlock them here (js/systems/unlocks.js). */\n'
  + 'G.OW_SPECIES = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(ROOT, 'micasurvivor/js/data/ow-species.js'), body);
console.log(`${Object.keys(out).length} ids -> ${dexes.size} species`);

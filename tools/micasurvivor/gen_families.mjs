// tools/micasurvivor/gen_families.mjs — MicaSurvivor DLC D18 (owner 2026-10-26: "i want both modes to respond to the same
// upgrades i can buy for the pokemon"): every species' evolution FAMILY, for the shared per-family upgrades.
// Writes micasurvivor/js/data/families.js (G.FAMILY: dex -> its family's root, for every species that has a pre-evolution).
// A family's root is the species with no pre-evolution: the overworld's evolution tables (overworld/data/species_extra.json
// `evos`) plus the same supplement js/expedition/league-data.js is generated with (tools/micasurvivor/gen_league.mjs: the
// evolutions the Gen 1-4 era tables don't carry). Forms map to their base species (the shortest key with that number).
//   node tools/micasurvivor/gen_families.mjs [--check]   (--check: exit 1 if the committed file differs)
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../');
const AROOT = process.env.MAGEPUNK_ASSET_ROOT ? path.resolve(process.env.MAGEPUNK_ASSET_ROOT) : ROOT;
const OUT = path.join(ROOT, 'micasurvivor/js/data/families.js');
const battle = JSON.parse(fs.readFileSync(path.join(AROOT, 'overworld/data/species_battle.json'), 'utf8'));
const extra = JSON.parse(fs.readFileSync(path.join(AROOT, 'overworld/data/species_extra.json'), 'utf8'));
const KEY = {};
for (const [k, s] of Object.entries(battle)) if (s.num > 0 && s.num <= 1025 && (!KEY[s.num] || k.length < KEY[s.num].length)) KEY[s.num] = k;
const numOf = k => (battle[k] && battle[k].num) || 0;
// (= gen_league.mjs SUPPLEMENT's targets)
const SUPPLEMENT = { linoone: ['obstagoon'], primeape: ['annihilape'], ursaring: ['ursaluna'], piloswine: ['mamoswine'], mimejr: ['mrmime'],
	mrmime: ['mrrime'], scyther: ['kleavor'], flabebe: ['floette'], steenee: ['tsareena'], pawmo: ['pawmot'], dipplin: ['hydrapple'],
	kubfu: ['urshifu'], meltan: ['melmetal'],
	// (and the later cross-generation evolutions the tables don't carry either: Gen 6 Sylveon; Gen 8 Galar's; Legends: Arceus'; Gen 9's)
	eevee: ['sylveon'], meowth: ['perrserker'], corsola: ['cursola'], farfetchd: ['sirfetchd'], yamask: ['runerigus'], stantler: ['wyrdeer'],
	basculin: ['basculegion'], sneasel: ['sneasler'], qwilfish: ['overqwil'], wooper: ['clodsire'], girafarig: ['farigiraf'], dunsparce: ['dudunsparce'],
	bisharp: ['kingambit'], gimmighoul: ['gholdengo'] };
const parent = {};
for (let d = 1; d <= 1025; d++) {
	const k = KEY[d];
	if (!k) continue;
	const targets = ((extra[k] && extra[k].evos) || []).map(e => e.target).concat(SUPPLEMENT[k] || []);
	for (const t of targets) {
		const to = numOf(t);
		if (!to || to > 1025 || to === d || KEY[to] !== t) continue;   // (forms: Lycanroc Midnight, Toxtricity Low Key...)
		if (parent[to] == null || parent[to] > d) parent[to] = d;
	}
}
const rootOf = d => { let r = d, n = 0; while (parent[r] != null && n++ < 5) r = parent[r]; return r; };
const fam = {};
for (let d = 1; d <= 1025; d++) { const r = rootOf(d); if (r !== d) fam[d] = r; }
const roots = new Set(Array.from({ length: 1025 }, (_, i) => rootOf(i + 1)));
const body = Object.entries(fam).map(([d, r]) => d + ':' + r).join(',');
const text = `/* ============ families.js — GENERATED by tools/micasurvivor/gen_families.mjs, do not edit ============
 * MicaSurvivor DLC D18: every species' evolution family, for the per-family upgrades (owner 2026-10-26: "both modes to respond
 * to the same upgrades i can buy for the pokemon"). G.FAMILY[dex] = the family's root (the species with no pre-evolution), for
 * the ${Object.keys(fam).length} species that have one; a root maps to itself (absent). ${roots.size} families in all.
 */
G.FAMILY = {${body}};
G.Families = (() => {
  const rootOf = d => G.FAMILY[d] || +d;
  let byRoot = null;
  /** Every species of dex's family (its root first), as numbers. */
  function membersOf(d) {
    if (!byRoot) { byRoot = {}; for (const k in G.FAMILY) (byRoot[G.FAMILY[k]] = byRoot[G.FAMILY[k]] || []).push(+k); }
    const r = rootOf(d);
    return [r].concat(byRoot[r] || []);
  }
  return { rootOf, membersOf };
})();
`;
const crlf = text.replace(/\n/g, '\r\n');
if (process.argv.includes('--check')) {
	const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
	if (cur !== text) { console.log('families.js is stale: node tools/micasurvivor/gen_families.mjs'); process.exit(1); }
	console.log('families.js is current'); process.exit(0);
}
fs.writeFileSync(OUT, crlf);
console.log(`${path.relative(ROOT, OUT)}: ${Object.keys(fam).length} species with a pre-evolution, ${roots.size} families (${text.length} chars)`);

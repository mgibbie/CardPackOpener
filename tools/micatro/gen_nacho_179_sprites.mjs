// Nacho's Pokermon Dip 1.7.9 sprites (Plans/MICATRO_MODS_UPGRADES.md batches 18-19): 1.7.9 no longer ships its own
// PokemonSprites entries (1.6.4's src/pokemon.lua did); every Nacho joker without its own `atlas` draws from Pokermon's sheets
// through pokermon.sprites.load_atlas / load_sprites (3.9.1 functions/pokespriteload.lua: PokemonSprites[name] -> the sheet
// get_atlas_string names + the cell, which wins over the item's own pos). This writes that lookup, resolved, for every 1.7.9
// Nacho joker, into micatro/mods/nacho/sprites179.js (GENERATED: never hand-edit).
//
//   1. the Nacho 1.7.9 extract: micatro/mods/nacho/data179.js (tools/micatro/extract_mod_data.cjs + specs/nacho_179.json)
//   2. the Pokermon 3.9.1 extract (the same one data391.js is generated from):
//        NODE_PATH=<fengari> node tools/micatro/extract_mod_data.cjs <Pokermon 3.9.1> <tmp>/pokermon391.js tools/micatro/specs/pokermon_391.json
//   3. node tools/micatro/gen_nacho_179_sprites.mjs <tmp>/pokermon391.js
// It fails when a 1.7.9 joker has neither its own atlas nor a 3.9.1 PokemonSprites entry (owner rule: no placeholder art).
import fs from 'fs';
import path from 'path';
import { pathToFileURL } from 'url';

const SRC = process.argv[2];
if (!SRC) { console.error('usage: node tools/micatro/gen_nacho_179_sprites.mjs <Pokermon 3.9.1 extract .js>'); process.exit(1); }
const P391 = (await import(pathToFileURL(path.resolve(SRC)).href)).default;
const N179 = (await import(pathToFileURL(path.resolve('micatro/mods/nacho/data179.js')).href)).default;
const SPR = {};
for (const s of (P391.globals.PokemonSprites && P391.globals.PokemonSprites.list) || []) SPR[s.name] = s;
const atlasOf = (s) => 'AtlasJokersBasic' + (s.gen_atlas ? (s.gen_atlas < 10 ? 'Gen0' : 'Gen') + s.gen_atlas : s.others_atlas ? 'Others' : 'Natdex');
const out = {};
const missing = [];
for (const f of N179.groups.jokers) {
  if (f.ret.can_load === false) continue; // (deprecated / never loaded upstream: not ported)
  for (const it of f.ret.list || []) {
    if (it.atlas) continue; // its own atlas + pos (index.js)
    const s = SPR[it.name];
    if (!s) { missing.push(it.name); continue; }
    const pos = s.base.pos.x !== undefined ? s.base.pos : s.base.pos[0];
    out[it.name] = { atlas: atlasOf(s), pos: { x: pos.x, y: pos.y }, ...(s.base.soul_pos ? { soul_pos: { x: s.base.soul_pos.x, y: s.base.soul_pos.y } } : {}) };
  }
}
if (missing.length) throw new Error('no 3.9.1 PokemonSprites entry: ' + missing.join(', '));
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n');
const src = `// GENERATED by tools/micatro/gen_nacho_179_sprites.mjs from Pokermon 3.9.1 functions/pokespriteload.lua — do not edit by hand.
// Nacho 1.7.9's jokers draw from Pokermon's sheets (pokermon.sprites.load_atlas / load_sprites): name -> the 3.9.1 sheet
// (registered by Pokermon as poke_<atlas>391) and cell. Jokers with their own atlas (Excavator, Palafin-Hero, Mega Baxcalibur,
// Terapagos-Stellar) are not listed: index.js reads theirs from data179.js.
export default {
${body}
};
`;
fs.writeFileSync('micatro/mods/nacho/sprites179.js', src.replace(/\n/g, '\r\n'));
console.log('wrote micatro/mods/nacho/sprites179.js (' + Object.keys(out).length + ' jokers)');

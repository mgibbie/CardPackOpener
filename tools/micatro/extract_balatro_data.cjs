// Extracts Balatro's content prototypes (game.lua init_item_prototypes + the
// hands table + en-us localization) into micatro/data/*.json using a Lua VM.
// Usage: node tools/micatro/extract_balatro_data.cjs "<balatro_extracted dir>"
// (fengari must be resolvable: NODE_PATH=<dir with node_modules/fengari>)
const fs = require('fs'), path = require('path');
const { lua, lauxlib, lualib, to_luastring, to_jsstring } = require('fengari');
const SRC = process.argv[2];
const OUT = path.join(__dirname, '..', '..', 'micatro', 'data');
const game = fs.readFileSync(path.join(SRC, 'game.lua'), 'utf8').split(/\r?\n/);
const start = game.findIndex(l => l.includes('self.P_SEALS = {'));
const end = game.findIndex((l, i) => i > start && l.includes('self.P_CENTER_POOLS = {'));
const handsStart = game.findIndex(l => /^\s+hands = \{\s*$/.test(l));
let handsEnd = handsStart; while (!/^\s{8}\}\s*$/.test(game[handsEnd])) handsEnd++;
const loc = fs.readFileSync(path.join(SRC, 'localization', 'en-us.lua'), 'utf8');
const prelude = `
local function HEX(h) return '#'..h end
function localize(k) return k end
G = {C = setmetatable({}, {__index=function() return {0,0,0,1} end})}
local self = {}
`;
const json = `
local function enc(v)
  local t = type(v)
  if t == 'nil' then return 'null' elseif t == 'boolean' then return tostring(v)
  elseif t == 'number' then if v ~= v or v == math.huge or v == -math.huge then return 'null' end return string.format('%.14g', v)
  elseif t == 'string' then return string.format('%q', v):gsub('\\\n','\\n')
  elseif t == 'table' then
    local n = #v; local isArr = n > 0
    if isArr then for k in pairs(v) do if type(k) ~= 'number' then isArr = false break end end end
    local parts = {}
    if isArr then for i=1,n do parts[#parts+1] = enc(v[i]) end return '['..table.concat(parts, ',')..']' end
    local keys = {} for k in pairs(v) do if type(k)=='string' or type(k)=='number' then keys[#keys+1]=k end end
    table.sort(keys, function(a,b) return tostring(a) < tostring(b) end)
    for _,k in ipairs(keys) do parts[#parts+1] = string.format('%q', tostring(k))..':'..enc(v[k]) end
    return '{'..table.concat(parts, ',')..'}'
  end
  return 'null'
end
`;
const code = prelude + game.slice(start, end).join('\n') +
  '\nlocal HANDS = {\n' + game.slice(handsStart + 1, handsEnd).join('\n') + '\n}\n' +
  'local LOC = (function() ' + loc.replace(/^\uFEFF/, '') + ' end)()\n' + json +
  `return enc({seals=self.P_SEALS, tags=self.P_TAGS, stakes=self.P_STAKES, blinds=self.P_BLINDS, cards=self.P_CARDS, centers=self.P_CENTERS, hands=HANDS, loc={descriptions=LOC.descriptions, misc=LOC.misc}})`;
const L = lauxlib.luaL_newstate(); lualib.luaL_openlibs(L);
if (lauxlib.luaL_loadstring(L, to_luastring(code)) !== 0 || lua.lua_pcall(L, 0, 1, 0) !== 0) {
  console.error(to_jsstring(lua.lua_tostring(L, -1))); process.exit(1);
}
const all = JSON.parse(to_jsstring(lua.lua_tostring(L, -1)));
fs.mkdirSync(OUT, { recursive: true });
for (const [k, v] of Object.entries(all)) {
  fs.writeFileSync(path.join(OUT, k + '.json'), JSON.stringify(v, null, 0));
  console.log(k, Object.keys(v).length);
}
// Single ES module so the browser and node tests import the same data with no fetch.
fs.writeFileSync(path.join(OUT, 'balatro_data.js'),
  '// GENERATED by tools/micatro/extract_balatro_data.cjs from Balatro\'s game.lua + en-us.lua. Do not edit.\n' +
  'export default ' + JSON.stringify(all) + ';\n');
for (const k of Object.keys(all)) fs.unlinkSync(path.join(OUT, k + '.json'));

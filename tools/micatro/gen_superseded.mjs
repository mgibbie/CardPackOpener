// Regenerates micatro/js/mods/superseded.js: the add-on jokers Pokermon supersedes (Pokermon PORTING.md "Add-on dedupe
// (Pokermon precedence)"), detected by the same rule the game uses (mods/pokermon/systems/precedence.js replaced_by):
// every registered joker of every shipped mod, loaded together with Pokermon. The win stickers read this static table
// (stickers.js runs on screens where no mod is loaded: the design wiki, a spectator before the mods arrive).
// micatro/tests/mods/addon_sticker_merge_test.mjs fails when the table drifts from the detection.
//   node tools/micatro/gen_superseded.mjs
globalThis.localStorage = globalThis.localStorage || { getItem() { return null; }, setItem() {}, removeItem() {} };
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const { P_CENTERS } = await import('../../micatro/js/engine/core.js');
const { AVAILABLE } = await import('../../micatro/js/mods/index.js');
for (const m of AVAILABLE) await m.load();   // every shipped mod (Pokermon first: AVAILABLE's order)
const { replaced_by } = await import('../../micatro/mods/pokermon/api.js');

/** {legacyKey: pokermonKey}, sorted by key. Exported for the sync test. */
export function detect() {
  const out = {};
  for (const k of Object.keys(P_CENTERS).sort()) { const to = replaced_by(k); if (to) out[k] = to; }
  return out;
}
const FILE = path.join(ROOT, 'micatro/js/mods/superseded.js');
const map = detect();
const body = Object.entries(map).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
const src = `// GENERATED by tools/micatro/gen_superseded.mjs — do not edit by hand (addon_sticker_merge_test checks it).
//
// The add-on jokers base Pokermon supersedes (Pokermon PORTING.md "Add-on dedupe (Pokermon precedence)"): a legacy
// Nacho / Pokermon+ key -> its Pokermon twin, as mods/pokermon/systems/precedence.js replaced_by detects it. The keys
// stay registered (legacy definitions); the win stickers (ui/stickers.js) count a legacy key's record toward its twin
// when they are READ, and a new win with a legacy card is recorded on both. Like aliases.js, this file has no imports.
export const SUPERSEDED = Object.freeze({
${body}
});
const FROM = Object.create(null);   // pokermon key -> [legacy keys]
for (const [k, v] of Object.entries(SUPERSEDED)) (FROM[v] || (FROM[v] = [])).push(k);
/** The Pokermon key a legacy add-on key is superseded by, else undefined. */
export const supersededBy = (key) => (typeof key === 'string' && Object.prototype.hasOwnProperty.call(SUPERSEDED, key) ? SUPERSEDED[key] : undefined);
/** The legacy add-on keys a Pokermon key supersedes ([] for none). */
export const supersededFrom = (key) => (typeof key === 'string' && FROM[key] ? FROM[key].slice() : []);
`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== src) { console.log('superseded.js is stale: node tools/micatro/gen_superseded.mjs'); process.exit(1); }
  console.log('superseded.js is up to date (' + Object.keys(map).length + ' keys)');
} else {
  fs.writeFileSync(FILE, src.replace(/\n/g, '\r\n'));
  console.log('wrote ' + path.relative(ROOT, FILE) + ' (' + Object.keys(map).length + ' keys)');
}

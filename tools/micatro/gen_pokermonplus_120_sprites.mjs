// Pokermon+ 1.2.0 sprites (Plans/MICATRO_MODS_UPGRADES.md batch 20): every 1.2.0 Pokermon+ joker without its own `atlas` draws
// from Pokermon's sheets (1.2.0 loaders/pokemon.lua: pokermon.sprites.load_sprites / load_atlas — 3.9.1
// functions/pokespriteload.lua: PokemonSprites[name] -> the sheet get_atlas_string names + the cell, which wins over the
// item's own pos). This writes that lookup, resolved, for every 1.2.0 joker into micatro/mods/pokermonplus/sprites120.js
// (GENERATED: never hand-edit). Lechonk / Cetoddle's `custom_art` asks for 3.9.1's "Series A" alt art, which Micatro doesn't
// ship (as in 1.0.3): they take the Basic cell like every other joker.
//
//   1. the Pokermon+ 1.2.0 extract: micatro/mods/pokermonplus/data120.js (tools/micatro/extract_mod_data.cjs + specs/pokermonplus_120.json)
//   2. the Pokermon 3.9.1 extract (the same one data391.js is generated from):
//        NODE_PATH=<fengari> node tools/micatro/extract_mod_data.cjs <Pokermon 3.9.1> <tmp>/pokermon391.js tools/micatro/specs/pokermon_391.json
//   3. node tools/micatro/gen_pokermonplus_120_sprites.mjs <tmp>/pokermon391.js
// It fails when a 1.2.0 joker has neither its own atlas nor a 3.9.1 PokemonSprites entry (owner rule: no placeholder art).
import fs from 'fs';
import path from 'path';
import { pathToFileURL } from 'url';

const SRC = process.argv[2];
if (!SRC) { console.error('usage: node tools/micatro/gen_pokermonplus_120_sprites.mjs <Pokermon 3.9.1 extract .js>'); process.exit(1); }
const P391 = (await import(pathToFileURL(path.resolve(SRC)).href)).default;
const D120 = (await import(pathToFileURL(path.resolve('micatro/mods/pokermonplus/data120.js')).href)).default;
const SPR = {};
for (const s of (P391.globals.PokemonSprites && P391.globals.PokemonSprites.list) || []) SPR[s.name] = s;
const atlasOf = (s) => 'AtlasJokersBasic' + (s.gen_atlas ? (s.gen_atlas < 10 ? 'Gen0' : 'Gen') + s.gen_atlas : s.others_atlas ? 'Others' : 'Natdex');
const out = {};
const missing = [];
for (const f of D120.groups.jokers) {
  for (const it of Array.isArray(f.ret.list) ? f.ret.list : []) {
    if (it.atlas) continue; // its own atlas + pos (index.js: sonfive_other)
    const s = SPR[it.name];
    if (!s) { missing.push(it.name); continue; }
    const pos = s.base.pos.x !== undefined ? s.base.pos : s.base.pos[0];
    out[it.name] = { atlas: atlasOf(s), pos: { x: pos.x, y: pos.y }, ...(s.base.soul_pos ? { soul_pos: { x: s.base.soul_pos.x, y: s.base.soul_pos.y } } : {}) };
  }
}
if (missing.length) throw new Error('no 3.9.1 PokemonSprites entry: ' + missing.join(', '));
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n');
const src = `// GENERATED by tools/micatro/gen_pokermonplus_120_sprites.mjs from Pokermon 3.9.1 functions/pokespriteload.lua — do not edit by hand.
// Pokermon+ 1.2.0's jokers draw from Pokermon's sheets (pokermon.sprites.load_atlas / load_sprites): name -> the 3.9.1 sheet
// (registered by Pokermon as poke_<atlas>391) and cell. Jokers with their own atlas (Mega Darkrai, Canari Plush, the Member
// Card, the Mystery Box: sonfive_other) are not listed: index.js reads theirs from data120.js.
export default {
${body}
};
`;
fs.writeFileSync('micatro/mods/pokermonplus/sprites120.js', src.replace(/\n/g, '\r\n'));
console.log('wrote micatro/mods/pokermonplus/sprites120.js (' + Object.keys(out).length + ' jokers)');

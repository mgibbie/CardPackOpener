// gen_pocket_looks.mjs — two small tables the card faces of Pocket Enhanced are drawn from (pocketenhanced/js/data/looks.js):
//
//   LOOKS  printing id -> how that printing is drawn. The rarity in data/packs.js says how rare a printing is; two
//          different kinds of printing share the two-star rarity (a full-art card and a rainbow one), so the kind
//          is taken from the open dataset pokemon-tcg-pocket-database (github.com/flibustier, MIT), whose rarity
//          codes keep them apart:  AR art (an illustration that fills the card) · SR full (full art) · SAR rainbow ·
//          IM immersive · UR gold (crown) · S shiny · SSR shiny, full art.  A printing the dataset does not list, or
//          lists as a diamond card, has no entry: it is drawn with the standard frame.
//   DEX    National Pokédex number -> [species name, its category ("Flame Pokémon"), height in decimetres, weight in
//          hectograms], from PokeAPI's open tables (github.com/PokeAPI/pokeapi, data/v2/csv). The strip under a card's
//          art prints them as Pocket does. Only the default form of a species is listed, so the game prints them
//          only on a card whose name IS the species' name (not on an Alolan or a Mega form, whose figures differ).
//
// Nothing is taken from either source but these facts: no images, no flavour text, no illustrator credits.
//   node tools/gen_pocket_looks.mjs            (fetches; writes pocketenhanced/js/data/looks.js)
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UA = { 'user-agent': 'generic-client' };
const get = async u => { for (let i = 0; i < 4; i++) { try { const r = await fetch(u, { headers: UA }); if (r.ok) return await r.text(); } catch (e) { /* retry */ } await new Promise(r => setTimeout(r, 800 * (i + 1))); } throw new Error('could not fetch ' + u); };
const { PRINTS } = await import(pathToFileURL(path.join(ROOT, 'pocketenhanced/js/data/packs.js')).href);

// ---- looks
const KIND = { AR: 'art', SR: 'full', SAR: 'rainbow', IM: 'immersive', UR: 'gold', S: 'shiny', SSR: 'shinyfull' };
const WANT = { art: ['1S'], full: ['2S'], rainbow: ['2S'], immersive: ['3S'], gold: ['CR'], shiny: ['1H'], shinyfull: ['2H'] };   // (the rarity each kind must have here: a disagreement is reported, not papered over)
const cards = JSON.parse(await get('https://raw.githubusercontent.com/flibustier/pokemon-tcg-pocket-database/main/dist/cards.json'));
const byId = new Map(cards.map(c => [`${c.set.replace(/^PROMO-/, 'P-')}-${String(c.number).padStart(3, '0')}`, c]));
const looks = {}, odd = [], missing = [];
for (const [id, , rar] of PRINTS) {
	if (/D$|F$|^N$/.test(rar)) continue;
	const d = byId.get(id);
	if (!d) { missing.push(id); continue; }
	const k = KIND[d.rarity];
	if (!k || !WANT[k].includes(rar)) { odd.push(`${id}: ${rar} here, ${d.rarity} in the dataset`); continue; }
	looks[id] = k;
}
if (odd.length) console.log(`${odd.length} printing(s) whose rarity disagrees (left with the standard treatment of their rarity):\n  ` + odd.slice(0, 20).join('\n  '));
if (missing.length) console.log(`${missing.length} star printing(s) the dataset does not list: ${missing.slice(0, 12).join(', ')}`);

// ---- the Pokédex facts
const csv = t => t.trim().split(/\r?\n/).slice(1).map(l => l.split(','));
const [names, mons] = await Promise.all([get('https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv'), get('https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon.csv')]);
const dex = {};
for (const [id, lang, name, genus] of csv(names)) if (lang === '9' && genus) dex[+id] = [name, genus];
for (const [, , species, h, w, , , isDefault] of csv(mons)) if (isDefault === '1' && dex[+species] && +h > 0 && +w > 0) dex[+species].push(+h, +w);
for (const k of Object.keys(dex)) if (dex[k].length !== 4) delete dex[k];

const count = {}; for (const k of Object.values(looks)) count[k] = (count[k] || 0) + 1;
const out = `// GENERATED by tools/gen_pocket_looks.mjs — do not edit.
// LOOKS: printing id -> how it is drawn (art · full · rainbow · immersive · gold · shiny · shinyfull), from the open
// dataset pokemon-tcg-pocket-database (MIT). DEX: Pokédex number -> [name, category, height (dm), weight (hg)], from
// PokeAPI's open tables. See the tool for what each means and what is deliberately not taken.
export const LOOKS = Object.freeze(${JSON.stringify(looks)});
export const DEX = Object.freeze(${JSON.stringify(dex)});
`;
fs.writeFileSync(path.join(ROOT, 'pocketenhanced/js/data/looks.js'), out);
console.log(`wrote looks.js: ${Object.keys(looks).length} printings (${Object.entries(count).map(([k, n]) => `${k} ${n}`).join(', ')}), ${Object.keys(dex).length} species`);

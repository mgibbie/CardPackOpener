// gen_values_species.mjs — writes site/values_species.js: every species' base value in stars, by speciesBase() in
// site/values.js (the formula lives there, and only there; this gathers the facts it reads).
//
//   node tools/gen_values_species.mjs            write it
//   node tools/gen_values_species.mjs --check    exit 1 if the committed table is not what the data gives now
//
// The facts, per species id of overworld/data/species_battle.json:
//   num, bst     species_battle.json
//   catch        species_extra.json `catch` (null where it has none)
//   stage        evolutions before it, from species_extra.json `evos` and fakemon_evos.js; a form (the same dex number)
//                takes the stage of the species it is a form of
//   wild         the best share, in percent, that the line's FIRST species has of any one wild table: data/encounters.json
//                and the generated tables in code (day/night, the postgame rosters)
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const D = path.join(ROOT, 'overworld', 'data');
const read = f => JSON.parse(fs.readFileSync(path.join(D, f), 'utf8'));
const OUT = path.join(ROOT, 'site', 'values_species.js');

export async function buildTable() {
	// (values.js imports the table this writes: give it an empty one while it is being made, so a missing file cannot stop it)
	const { speciesBase } = await import(pathToFileURL(path.join(ROOT, 'site', 'values.js')).href);
	const { FAKEMON_EVOS } = await import(pathToFileURL(path.join(ROOT, 'overworld', 'fakemon_evos.js')).href);
	const bat = read('species_battle.json'), ext = read('species_extra.json'), enc = read('encounters.json');
	const ids = Object.keys(bat).filter(k => !k.startsWith('_')).sort();
	// who evolves into whom
	const parent = {};
	const noteEvos = (from, evos) => { for (const e of evos || []) if (e && e.target && bat[e.target] && !parent[e.target]) parent[e.target] = from; };
	for (const [id, x] of Object.entries(ext)) noteEvos(id, x.evos);
	for (const [id, evos] of Object.entries(FAKEMON_EVOS)) noteEvos(id, evos);
	const rootOf = id => { const seen = new Set(); while (parent[id] && !seen.has(id)) { seen.add(id); id = parent[id]; } return id; };
	const stageOwn = id => { let n = 0; const seen = new Set(); while (parent[id] && !seen.has(id) && n < 5) { seen.add(id); id = parent[id]; n++; } return n; };
	const byNum = {};
	for (const id of ids) (byNum[bat[id].num] = byNum[bat[id].num] || []).push(id);
	// wild shares
	const share = {};
	const table = slots => {
		const tot = slots.reduce((a, s) => a + (+s.w || 0), 0); if (!tot) return;
		const per = {}; for (const s of slots) per[s.id] = (per[s.id] || 0) + (+s.w || 0);
		for (const [id, w] of Object.entries(per)) share[id] = Math.max(share[id] || 0, (100 * w) / tot);
	};
	for (const t of Object.values(enc)) for (const kind of ['land', 'water', 'fishing', 'rock_smash']) if (t[kind] && Array.isArray(t[kind].slots)) table(t[kind].slots);
	for (const f of ['encounters_daynight.js', 'encounters_postgame.js', 'encounters_sinnoh_postgame.js', 'encounters_frem_night.js']) {
		const p = path.join(ROOT, 'overworld', f); if (!fs.existsSync(p)) continue;
		const src = fs.readFileSync(p, 'utf8');
		for (const m of src.matchAll(/\[((?:\s*\{\s*id:\s*'[a-z0-9_]+'[^{}]*\}\s*,?)+)\s*\]/g)) {
			table([...m[1].matchAll(/id:\s*'([a-z0-9_]+)'[^{}]*?\bw:\s*(\d+(?:\.\d+)?)/g)].map(q => ({ id: q[1], w: +q[2] })));
		}
	}
	const out = {};
	for (const id of ids) {
		const s = bat[id], b = s.baseStats || {};
		const bst = ['hp', 'atk', 'def', 'spa', 'spd', 'spe'].reduce((a, k) => a + (+b[k] || 0), 0);
		// a form takes its species' place in the line (the most-evolved id of its dex number that is in a line)
		const stage = Math.max(stageOwn(id), ...(byNum[s.num] || []).filter(x => x !== id && s.num > 0).map(stageOwn));
		const lineRoot = rootOf(id), formRoot = s.num > 0 ? (byNum[s.num] || []).map(rootOf).find(r => r !== id && share[r]) : null;
		const wild = Math.max(share[lineRoot] || 0, share[id] || 0, formRoot ? share[formRoot] : 0);
		const c = ext[id] && Number.isFinite(ext[id].catch) ? ext[id].catch : null;
		out[id] = speciesBase({ num: s.num, bst, catch: c, stage, wild });
	}
	return out;
}
export function render(table) {
	const lines = Object.entries(table).map(([id, v]) => `${JSON.stringify(id)}:${v}`);
	const rows = []; for (let i = 0; i < lines.length; i += 12) rows.push('\t' + lines.slice(i, i + 12).join(', ') + ',');
	return `// values_species.js — GENERATED by tools/gen_values_species.mjs from the overworld's species data; do not edit by hand.\n` +
		`// Each species' base value in stars (site/values.js speciesBase() is the formula; monValue() adds shiny, level and IVs).\n` +
		`export const SPECIES_BASE = Object.freeze({\n${rows.join('\n')}\n});\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	if (!fs.existsSync(OUT)) fs.writeFileSync(OUT, render({}));
	const table = await buildTable(), text = render(table);
	if (process.argv.includes('--check')) {
		const same = fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') === text;
		console.log(same ? 'site/values_species.js is up to date' : 'site/values_species.js is OUT OF DATE: run node tools/gen_values_species.mjs');
		process.exit(same ? 0 : 1);
	}
	fs.writeFileSync(OUT, text);
	console.log(`wrote ${path.relative(ROOT, OUT)} (${Object.keys(table).length} species)`);
}

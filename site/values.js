// values.js — what every tradeable thing on the site is worth, in STARS (★). The one place the site says it.
//
// Owner, 2026-11-19: "anything tradeable should be bettable. any card from battlecards or pocket, pokemon, pack, or item
// from the overworld should be tradeable. everything needs to have an equivalent value in stars. 1 star = 100p (the money
// from the overworld). 20 stars equals 1 dust. every single thing needs to have a star value."
// The owner's choices the same day: a card is worth what it BREAKS DOWN for in dust, x20; a Pokémon is worth its species'
// RARITY plus its LEVEL (shiny x10, a little for perfect IVs); KEY/STORY items stay untradeable; every other item is worth
// its shop price in P / 100, and an item no shop sells gets a value from what it does (NO_PRICE below).
//
// Every value is a whole number of stars, at least 1, for anything tradeable; something that cannot be traded is null.
// An amount (a stack of items, a pile of coins) is valued as a whole and then rounded, so 5 Shoal Salt at 20 P each
// are 1 ★, not 5 × 1 ★.
//
// Imported by the pages (the trade windows, the Inventory) AND by the server (server/trade.mjs shows each side's worth;
// bets will use it to price an item put into a pool), so it reads only data that both have: the overworld bag's ITEMS,
// Pocket's printings, and the species table site/values_species.js (generated by tools/gen_values_species.mjs from the
// overworld's species data, with speciesBase() below as its formula). A Battlecards card's rarity is the caller's to say
// (the server has server/pool-rarity.json, a page has /battlecards/cards.json: the two agree, the first is made from the second).
import { ITEMS } from '../overworld/bag.js';
import { printInfo, DUST_FOR } from '../pocketenhanced/js/collection.js';
import { STARS_PER_PACK } from './stars.js';
import { SPECIES_BASE } from './values_species.js';

// ---------------------------------------------------------------- the owner's ratios
export const STAR_PER_P = 1 / 100;            // 1 ★ = 100 P (overworld money)
export const STARS_PER_DUST = 20;             // 1 dust = 20 ★ (Battlecards and Pocket share dust)

// ---------------------------------------------------------------- the ratios derived from the games' own prices
// (the owner gave none for these; each is what the game itself charges, said in stars)
/** A pack (Battlecards or Pocket, of any booster) = what Pocket sells one for: 100 ★ (site/stars.js STARS_PER_PACK). */
export const STARS_PER_PACK_ANY = STARS_PER_PACK;
/** Battlecards gold: a Battlecards pack costs 150 gold (server/mp.mjs GOLD_PACK_PRICE, the owner's price), and a pack is
 *  100 ★, so 150 gold = 100 ★: 1 gold = 2/3 ★. */
export const GOLD_PACK_PRICE = 150;
export const STAR_PER_GOLD = STARS_PER_PACK / GOLD_PACK_PRICE;
/** Game Corner coins: the Game Corner counter sells 50 coins for $1,000 (overworld/ow_gamecorner.js), so 1 coin = 20 P
 *  = 1/5 ★. */
export const P_PER_GC_COIN = 1000 / 50;
export const STAR_PER_GC_COIN = P_PER_GC_COIN * STAR_PER_P;
/** MicaSurvivor tickets: nothing sells them. A ticket is one gacha pull, which gives one Pokémon. First set as one card
 *  of a five-card pack (1/5 of a pack = 20 ★); the owner (2026-11-19) made MicaSurvivor's things worth 10x that:
 *  200 ★ a ticket, 2,000 ★ a 10-pull ticket. */
export const MS_VALUE_X = 10;   // (owner, 2026-11-19: "10x the value of the micasurvivor stuff")
export const STARS_PER_MS_TICKET = STARS_PER_PACK / 5 * MS_VALUE_X;
export const STARS_PER_MS_TICKET10 = STARS_PER_MS_TICKET * 10;
/** MicaSurvivor coins: nothing sells them either. A pull that gives a Pokémon already owned is paid back in coins
 *  (micasurvivor/js/systems/gacha.js REFUND by rarity, rolled at its RATES): 0.45×15 + 0.30×30 + 0.17×60 + 0.065×120
 *  + 0.015×300 = 38.25 coins on average, for a pull first worth 20 ★: 0.52 ★ a coin, 2 coins = 1 ★; at the owner's 10x
 *  (MS_VALUE_X) 1 coin = 5 ★. */
export const STAR_PER_MS_COIN = 1 / 2 * MS_VALUE_X;

// ---------------------------------------------------------------- cards
/** Battlecards: what a card breaks down for (server/mp.mjs dust-extras; also the dust paid for a copy past the 999 an
 *  account may own). The one Mythic card breaks down as a Legendary; a card outside the pack pool (a token, a starter
 *  card, an uncollectible one) for the dust its printed rarity would give, Common when it has none. */
export const BC_DUST = Object.freeze({ common: 5, uncommon: 10, rare: 20, epic: 100, legendary: 400 });
const BC_ALIAS = { mythic: 'legendary' };
export const bcDust = rarity => BC_DUST[BC_ALIAS[rarity] || rarity] || BC_DUST.common;
/** Pocket: what a printing breaks down for (pocketenhanced/js/collection.js DUST_FOR). A promo cannot be broken down;
 *  it is valued as a one-diamond card (5 dust), the commonest card a pack holds. */
export const PK_PROMO_DUST = DUST_FOR['1D'];
export function pkDust(printId) { const p = printInfo(printId); if (!p) return null; return DUST_FOR[p.rarity] || PK_PROMO_DUST; }

// ---------------------------------------------------------------- overworld items
/** Kinds that are KEY or STORY items (owner: these stay untradeable): key items, HMs, the Rift Prism (kind 'form', a
 *  dex reward) and the Shiny Charm (kind 'charm', a dex reward). */
export const UNTRADEABLE_KINDS = Object.freeze(['key', 'hm', 'form', 'charm']);
/** Items no shop sells (price 0), valued from what they do, in P (then /100 like any price):
 *  - Master Ball: catches anything. Five Ultra Balls' price could not buy it; set at 50,000 P.
 *  - Sport Ball: the Contest's ball, as good as a Great Ball (600 P).
 *  - Full Restore: heals fully and cures, its usual mart price, 3,000 P.
 *  - PP Up: its usual price, 9,800 P; PP Max: three PP Ups' worth (it does three stages at once).
 *  - Lucky Egg, Amulet Coin: lasting x1.5 exp / x2 prize money while held; 10,000 P each, as a Mega Stone.
 *  - Adamant / Lustrous Orb and the Primal orbs: a legendary's own held item; 10,000 P, as a Mega Stone.
 *  - Alola / Galar / Hisui Charm: steer an evolution to a regional form, held, never used up; 5,000 P (an Ability Capsule).
 *  - Odd Keystone: summons Spiritomb; 2,100 P, its usual price.
 *  - White / Black Flute: a reusable 250-step lure / repel; 1,000 P. Blue Flute: wakes its holder, a Chesto Berry's worth.
 */
export const NO_PRICE = Object.freeze({
	masterball: 50000, sportball: 600, fullrestore: 3000, ppup: 9800, ppmax: 29400, luckyegg: 10000, amuletcoin: 10000,
	adamantorb: 10000, lustrousorb: 10000, redorb: 10000, blueorb: 10000, alolacharm: 5000, galarcharm: 5000, hisuicharm: 5000,
	oddkeystone: 2100, whiteflute: 1000, blackflute: 1000, blueflute: 100,
});
/** An id the bag can hold that ITEMS does not define (a pickup from the decomp's scripts): a TM is a TM's usual 3,000 P,
 *  a few well-known valuables have their usual price, and anything else 1,000 P. One that reads like a key or story
 *  item (an HM, a key, a pass, a ticket, a card, a letter...) is untradeable. */
const UNKNOWN_KEYLIKE = /^hm\d*|key$|pass$|ticket$|card$|letter$|parcel$|scope$|bike$|goods$|part$|egg$|fossil$|amber$|meteorite$|ruby$|sapphire$/;
export const UNKNOWN_PRICES = Object.freeze({ nugget: 10000, bignugget: 40000, pearl: 1400, bigpearl: 7500, pearlstring: 30000, stardust: 2000, starpiece: 9800, cometshard: 25000, tinymushroom: 500, bigmushroom: 5000, balmmushroom: 25000, maxelixir: 4500, elixir: 3000, maxether: 2000, maxpotion: 2500, maxrevive: 4000, heartscale: 1000 });
export const UNKNOWN_PRICE = 1000, UNKNOWN_TM_PRICE = 3000;
/** One of an item, in P; null when it cannot be traded. */
export function itemPrice(id) {
	id = String(id || '');
	const it = ITEMS[id];
	if (it) { if (UNTRADEABLE_KINDS.includes(it.kind)) return null; return it.price > 0 ? it.price : NO_PRICE[id] || UNKNOWN_PRICE; }
	if (!id || UNKNOWN_KEYLIKE.test(id)) return null;
	return UNKNOWN_PRICES[id] || (/^tm\d*/.test(id) ? UNKNOWN_TM_PRICE : UNKNOWN_PRICE);
}
export const itemTradeable = id => itemPrice(id) != null;

// ---------------------------------------------------------------- Pokémon
// Canon's lists, by national dex number (a form shares its species' number).
export const MYTHICAL = Object.freeze([151, 251, 385, 386, 489, 490, 491, 492, 493, 494, 647, 648, 649, 719, 720, 721, 801, 802, 807, 808, 809, 893, 1025]);
export const LEGENDARY = Object.freeze([144, 145, 146, 150, 243, 244, 245, 249, 250, 377, 378, 379, 380, 381, 382, 383, 384, 480, 481, 482, 483, 484, 485, 486, 487, 488, 638, 639, 640, 641, 642, 643, 644, 645, 646, 716, 717, 718, 772, 773, 785, 786, 787, 788, 789, 790, 791, 792, 800, 888, 889, 890, 891, 892, 894, 895, 896, 897, 898, 905, 1001, 1002, 1003, 1004, 1007, 1008, 1014, 1015, 1016, 1017, 1024]);
export const ULTRA_BEAST_OR_PARADOX = Object.freeze([793, 794, 795, 796, 797, 798, 799, 803, 804, 805, 806, 984, 985, 986, 987, 988, 989, 990, 991, 992, 993, 994, 995, 1005, 1006, 1009, 1010, 1020, 1021, 1022, 1023]);
/** A species' base value in ★: the formula (tools/gen_values_species.mjs runs it over every species and writes the table).
 *  facts = { num: dex number (<= 0 for the Uranium / Ransei fakemon), bst: base stat total, catch: catch rate or null,
 *            stage: evolutions before it (0 for a line's first), wild: the best share, in percent, that its line's FIRST
 *            species has of any one wild encounter table (0 when it is found in none) }
 *  - Mythical 10,000 ★; a legendary 5,000 ★ with a base stat total of 670 or more (the box legendaries), else 2,000 ★;
 *    an Ultra Beast or a Paradox Pokémon 1,000 ★.
 *  - Anything else starts from its CATCH RATE, the games' own measure of how rare it is meant to be: 255-190 10 ★,
 *    189-120 20 ★, 119-60 40 ★, 59-25 80 ★, under 25 150 ★ (no catch rate known: read off its base stat total).
 *  - x2 when its line is found in no wild table, or in under 5% of one (a gift, a starter, a fossil, a rift fakemon, a
 *    rare slot); x1.5 when under 15%.
 *  - x1.5 for each evolution it is past its line's first (a stage-2 Venusaur is worth more than a Bulbasaur).
 */
export const CATCH_TIERS = Object.freeze([[190, 10], [120, 20], [60, 40], [25, 80], [0, 150]]);
const catchFromBst = bst => (bst < 300 ? 190 : bst < 400 ? 120 : bst < 500 ? 60 : bst < 580 ? 45 : 3);
export function speciesBase(f) {
	const num = f.num | 0, bst = f.bst || 0;
	if (MYTHICAL.includes(num)) return 10000;
	if (LEGENDARY.includes(num)) return bst >= 670 ? 5000 : 2000;
	if (ULTRA_BEAST_OR_PARADOX.includes(num)) return 1000;
	const c = Number.isFinite(f.catch) && f.catch > 0 ? f.catch : catchFromBst(bst);
	let v = CATCH_TIERS.find(([at]) => c >= at)[1];
	const wild = f.wild || 0;
	v *= wild < 5 ? 2 : wild < 15 ? 1.5 : 1;
	v *= Math.pow(1.5, Math.max(0, f.stage | 0));
	return Math.max(1, Math.round(v));
}
export const SHINY_MULT = 10;                 // owner: shiny x10 (of the species' base)
export const STARS_PER_LEVEL = 1;             // "a little per level": a Lv 100 adds 100 ★
export const STARS_PER_PERFECT_IV = 10;       // each stat at 31: up to 60 ★
export const UNKNOWN_SPECIES_BASE = 10;       // a species the table does not know (none today): as a common one
export function monValue(mon) {
	if (!mon || typeof mon !== 'object') return null;
	const base = SPECIES_BASE[mon.speciesId] || UNKNOWN_SPECIES_BASE;
	const ivs = mon.ivs && typeof mon.ivs === 'object' ? Object.values(mon.ivs).filter(v => v === 31).length : 0;
	const lv = Math.max(1, Math.min(1000, Math.floor(+mon.level) || 1));
	return Math.max(1, Math.round(base * (mon.shiny ? SHINY_MULT : 1) + lv * STARS_PER_LEVEL + Math.min(6, ivs) * STARS_PER_PERFECT_IV));
}

// ---------------------------------------------------------------- one call for everything
const amt = (n, per) => { n = Math.floor(+n) || 0; return n > 0 ? Math.max(1, Math.round(n * per)) : 0; };
/**
 * What a thing is worth, in whole stars (at least 1), or null when it cannot be traded.
 *   { kind: 'stars', n }                      { kind: 'dust', n }                  { kind: 'gold', n }
 *   { kind: 'bc-card', id, rarity, n }        { kind: 'bc-pack', n }
 *   { kind: 'pk-card', id, n }                { kind: 'pk-pack', n }               { kind: 'pk-booster', id, n }
 *   { kind: 'ms-coins', n }                   { kind: 'ms-t1', n }                 { kind: 'ms-t10', n }
 *   { kind: 'pokemon', mon }                  { kind: 'item', id, n }              { kind: 'money', n }   { kind: 'coins', n }
 * n defaults to 1. An amount of 0 is worth 0.
 */
export function starValue(t) {
	if (!t || typeof t !== 'object') return null;
	const n = t.n == null ? 1 : Math.floor(+t.n) || 0;
	switch (t.kind) {
		case 'stars': return amt(n, 1);
		case 'dust': return amt(n, STARS_PER_DUST);
		case 'gold': return amt(n, STAR_PER_GOLD);
		case 'money': return amt(n, STAR_PER_P);
		case 'coins': return amt(n, STAR_PER_GC_COIN);
		case 'ms-coins': return amt(n, STAR_PER_MS_COIN);
		case 'ms-t1': return amt(n, STARS_PER_MS_TICKET);
		case 'ms-t10': return amt(n, STARS_PER_MS_TICKET10);
		case 'bc-pack': case 'pk-pack': case 'pk-booster': return amt(n, STARS_PER_PACK_ANY);
		case 'bc-card': return amt(n, bcDust(t.rarity) * STARS_PER_DUST);
		case 'pk-card': { const d = pkDust(t.id); return d == null ? null : amt(n, d * STARS_PER_DUST); }
		case 'item': { const p = itemPrice(t.id); return p == null ? null : amt(n, p * STAR_PER_P); }
		case 'pokemon': return monValue(t.mon);
		default: return null;
	}
}

/** A trade offer (server/trade.mjs's shape), valued: each thing's worth and the total. bcRarity(id) says a Battlecards
 *  card's rarity. -> { total, cards:{id:★}, packs, dust, gold, stars, pk:{prints:{id:★}, packs, own:{id:★}},
 *  ms:{coins,t1,t10}, pokemon:[★], items:{id:★}, money, coins } (each the worth of all of it that is offered). */
export function offerWorth(o, bcRarity = () => null) {
	o = o || {};
	const w = { total: 0, cards: {}, packs: 0, dust: 0, gold: 0, stars: 0, pk: { prints: {}, packs: 0, own: {} }, ms: { coins: 0, t1: 0, t10: 0 }, pokemon: [], items: {}, money: 0, coins: 0 };
	const add = v => { w.total += v || 0; return v || 0; };
	for (const [id, n] of Object.entries(o.cards || {})) w.cards[id] = add(starValue({ kind: 'bc-card', id, rarity: bcRarity(id), n }));
	w.packs = add(starValue({ kind: 'bc-pack', n: o.packs || 0 }));
	w.dust = add(starValue({ kind: 'dust', n: o.dust || 0 }));
	w.gold = add(starValue({ kind: 'gold', n: o.gold || 0 }));
	w.stars = add(starValue({ kind: 'stars', n: o.stars || 0 }));
	const pk = o.pk || {};
	for (const [id, n] of Object.entries(pk.prints || {})) w.pk.prints[id] = add(starValue({ kind: 'pk-card', id, n }));
	w.pk.packs = add(starValue({ kind: 'pk-pack', n: pk.packs || 0 }));
	for (const [id, n] of Object.entries(pk.own || {})) w.pk.own[id] = add(starValue({ kind: 'pk-booster', id, n }));
	const ms = o.ms || {};
	w.ms.coins = add(starValue({ kind: 'ms-coins', n: ms.coins || 0 }));
	w.ms.t1 = add(starValue({ kind: 'ms-t1', n: ms.t1 || 0 }));
	w.ms.t10 = add(starValue({ kind: 'ms-t10', n: ms.t10 || 0 }));
	for (const m of o.pokemon || []) w.pokemon.push(add(starValue({ kind: 'pokemon', mon: m })));
	for (const it of o.items || []) w.items[it.id] = add(starValue({ kind: 'item', id: it.id, n: it.count }));
	w.money = add(starValue({ kind: 'money', n: o.money || 0 }));
	w.coins = add(starValue({ kind: 'coins', n: o.coins || 0 }));
	return w;
}
/** "1,234 ★" */
export const starText = n => (n == null ? '—' : `${Math.round(n).toLocaleString('en-US')} ★`);

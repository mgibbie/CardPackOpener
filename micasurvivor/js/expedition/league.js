G.ExpLeague = (() => {
  const D = G.EXP_LEAGUE_DATA;
  // ---------------- balance (tune here; README "DLC D4") ----------------
  const K = {
    KIT_AT: [1, 2, 4, 7],          // the kit's moves unlock at these levels (study 2.1)
    MATURE_AT: [24, 44], MATURE_K: 0.12,   // Maturity: +12 % damage and max HP each time
    HP0: 70, HP_K: 0.45,           // HP = 70 + 0.45 x base HP (the base game's own formula, = PokéBonk's 70 + 45 f)
    ARMOR_DEF: 6, ARMOR_SPD: 3, ARMOR_RED: 0.01, ARMOR_MAX: 0.2,   // armor = (6 def + 3 spd) / 100; 1 % less damage per point, cap 20 %
    SPD0: 105, SPD_A: 0.92, SPD_B: 0.12,   // speed = 105 x (0.92 + 0.12 spe / 100): 105 is the base game's speed at spe 65
    ATK0: 1.1, ATK_A: 0.82, ATK_B: 0.2,    // attack = 1.1 x (0.82 + 0.2 stat / 100): 1.045 at 65, the base game's 1.06
    EVO_FLOOR: 0.5, EVO_HEAL: 0.3,  // evolving: HP to at least 50 %, then +30 % of max
    ROLE: { healer: { regen: 0.6 }, assault: { atk: 0.08 }, defender: { taken: 0.06 }, speedster: { spd: 0.06 } },
    PLAY_MET: true,                // D4: a completed challenge plays at once (D8: it brings the wild encounter instead)
    DEFAULT: 1,                    // Bulbasaur
    PICK_KEY: 'micasurvivorexp_pick'
  };
  const RANK_NAME = { starter: 'Inicial', common: 'Común', uncommon: 'Poco común', rare: 'Rara', legendary: 'Legendaria' };
  const RANK_COL = { starter: '#7fd18b', common: '#b9c4d4', uncommon: '#6fb8ff', rare: '#c58bff', legendary: '#ffd23f' };
  const ROLE_NAME = { healer: 'Sanador', assault: 'Asalto', defender: 'Defensor', speedster: 'Veloz' };
  const ROLE_DESC = { healer: '+0,6 de vida por segundo', assault: '+8 % de daño', defender: '-6 % de daño recibido', speedster: '+6 % de velocidad' };
  // the real games' move classes (MicaSurvivor's moves have none): physical, status (no class scaling), else special
  const PHYS = new Set(['tackle', 'quick-attack', 'body-slam', 'vine-whip', 'razor-leaf', 'poison-sting', 'bulldoze', 'bonemerang', 'bug-bite',
    'rock-throw', 'rock-slide', 'karate-chop', 'lick', 'metal-claw', 'meteor-mash', 'bite', 'aerial-ace', 'wing-attack', 'flame-wheel', 'psycho-cut']);
  const STATUS = new Set(['swords-dance', 'agility', 'harden', 'aqua-ring', 'dragon-dance', 'toxic', 'toxic-spikes', 'spikes', 'string-shot',
    'will-o-wisp', 'substitute', 'hypnosis', 'hail']);

  // ---------------- the roster ----------------
  const BY = {}, FAM = {};
  for (const m of D.members) BY[m.dex] = m;
  /** Every stage of member m, the first one first. */
  function stagesOf(m) { const out = [m.dex], q = [m.dex]; while (q.length) { const d = q.shift(); for (const [to] of m.evo[d] || []) if (!out.includes(to)) { out.push(to); q.push(to); } } return out; }
  for (const m of D.members) for (const d of stagesOf(m)) FAM[d] = m.dex;
  const finalsOf = m => stagesOf(m).filter(d => !m.evo[d]);
  const nextOf = (m, d) => (m && m.evo[d]) || [];
  const evoLevel = (m, d) => { const n = nextOf(m, d); return n.length ? Math.min(...n.map(x => x[1])) : 0; };
  const ids = () => D.members.map(m => m.dex);
  const name = d => (G.DEX_BY[d] || {}).name || '#' + d;
  const T = G.I18n;

  // ---------------- stats from base stats (pure) ----------------
  /** {hp, armor, taken, spd, phys, spec, atk} of species d (its real base stats; study 2.1, K). */
  function statsOf(d) {
    const b = D.base[d] || [50, 50, 50, 50, 50, 50], [hp, atk, def, spa, spd, spe] = b;
    const armor = (K.ARMOR_DEF * def + K.ARMOR_SPD * spd) / 100;
    const phys = K.ATK0 * (K.ATK_A + K.ATK_B * atk / 100), spec = K.ATK0 * (K.ATK_A + K.ATK_B * spa / 100);
    return { hp: Math.round(K.HP0 + K.HP_K * hp), armor: Math.round(armor * 10) / 10, taken: Math.min(K.ARMOR_MAX, armor * K.ARMOR_RED),
             spd: Math.round(K.SPD0 * (K.SPD_A + K.SPD_B * spe / 100)), phys: +phys.toFixed(4), spec: +spec.toFixed(4), atk: +Math.max(phys, spec).toFixed(4) };
  }
  /** The move class: 'phys' / 'spec' / 'status'. */
  const classOf = id => { const x = G.ExpMoves && G.ExpMoves.MOVES[id]; if (x) return x.cls || 'spec'; return PHYS.has(id) ? 'phys' : STATUS.has(id) ? 'status' : 'spec'; };   // (D5: an Expedition move says its own)
  /** A move's damage factor for species stats st: its class's multiplier over the player's attack (the higher one). */
  const factorOf = (id, st) => { const c = classOf(id); return c === 'phys' ? st.phys / st.atk : c === 'spec' ? st.spec / st.atk : 1; };

  // ---------------- unlocks (the Expedition save) ----------------
  const Sv = () => G.ExpSave;
  const free = d => !!BY[d] && !BY[d].ch;
  const own = d => free(d) || Sv().has('league.own', d);
  const met = d => Sv().has('league.met', d);
  const playable = d => !!BY[d] && (own(d) || (K.PLAY_MET && met(d)));
  const roster = () => ids().filter(playable);
  /** The counters a challenge reads. */
  function counter(k, t) {
    const S = Sv(), c = S.data.counters;
    if (k === 'runs') return S.get('runs');
    if (k === 'zone') { let z = 0; for (const n in c) if (/^zone\./.test(n)) z = Math.max(z, c[n]); return z; }
    if (k === 'wins') { let w = 0; for (const n in c) if (/^wins\./.test(n)) w += c[n]; return w; }
    if (k === 'ko') return S.get('kos');
    if (k === 'kot') return S.get('ko.t.' + t);
    if (k === 'guard') return S.get('guardians');
    if (k === 'evo') return S.get('lg.evo');
    if (k === 'mat') return S.get('lg.mat');
    if (k === 'lv') return S.get('lg.lv');
    if (k === 'league') return roster().length;
    return 0;
  }
  function chText(c) {
    const tn = t => G.U.TYPE_NAME[t] || t;
    switch (c.k) {
      case 'runs': return c.n === 1 ? T.t('Termina 1 partida de Expedición') : T.f('Termina {x} partidas de Expedición', c.n);
      case 'zone': return T.f('Llega a la zona {x}', c.n);
      case 'wins': return c.n === 1 ? T.t('Gana un mapa') : T.f('Gana un mapa {x} veces', c.n);
      case 'ko': return T.f('Derrota a {x} Pokémon en la Expedición', c.n);
      case 'kot': return T.f('Derrota a {x} Pokémon con un miembro de tipo {x}', c.n, T.t(tn(c.t)));
      case 'guard': return T.f('Vence a {x} guardianes', c.n);
      case 'evo': return T.f('Evoluciona {x} veces', c.n);
      case 'mat': return T.f('Alcanza la madurez {x}', c.n);
      case 'lv': return T.f('Llega al nivel {x} en una partida', c.n);
      case 'league': return T.f('Ten {x} miembros de la Liga', c.n);
    }
    return '';
  }
  /** A challenge's progress: {done, parts: [{text, have, need}]} (null challenge: free). */
  function progress(ch) {
    if (!ch) return { done: true, parts: [] };
    const parts = (ch.all || [ch]).map(c => ({ text: chText(c), have: Math.min(c.n, counter(c.k, c.t)), need: c.n }));
    return { done: parts.every(p => p.have >= p.need), parts };
  }
  /** After a run: every member whose challenge is now complete joins league.met. -> the newly met dex list */
  function checkChallenges() {
    const out = [];
    // (two passes: "have N League members" can be completed by the first pass's new members)
    for (let pass = 0; pass < 2; pass++) for (const m of D.members) {
      if (!m.ch || met(m.dex) || Sv().has('league.own', m.dex)) continue;
      if (progress(m.ch).done && Sv().add('league.met', m.dex)) out.push(m.dex);
    }
    return out;
  }

  // ---------------- the pick (this device) ----------------
  function readPick() { try { return +localStorage.getItem(K.PICK_KEY) || 0; } catch (e) { return 0; } }
  function setPick(d) { if (!playable(d)) return false; try { localStorage.setItem(K.PICK_KEY, String(d)); } catch (e) { /* the pick is a convenience */ } return true; }
  /** The member a new run of `mode` starts with (G.Modes.plan): your pick if you can play it, else Bulbasaur. */
  const pickFor = () => { const d = readPick(); return playable(d) ? d : K.DEFAULT; };

  // ---------------- the run ----------------
  let S = null;   // {member, form, kit, mat, evo, done, pending, note, st, ability, role, log}
  const on = pl => !!(S && G.Modes.isExp() && pl && pl === G.Game.player && !pl.remote);

  /** The player's body becomes species d (sprite, size, types, the verbs' cache); the passive stays the member's. */
  function body(p, d) {
    const dir = p.anim ? p.anim.dir : 0;
    p.dex = d;
    p.anim = new G.Sprites.Animator(d, 1, p.shiny && G.Sprites.hasShiny(d));
    p.anim.dir = dir;
    p.r = G.Sprites.bodyRadius(d);
    p.bodyH = G.Sprites.bodyHeight(d);
    G.Sprites.preload([d], 8000, p.shiny);
  }
  /** The stage's stats on the player: HP, armor, speed and attack from its base stats (the rest of its bonuses kept). */
  function applyStats(pl, d, prev, hp0) {
    const st = statsOf(d), mon = Object.assign({}, G.DEX_BY[d], { hp: st.hp, spd: st.spd, atk: st.atk });
    pl.mon = mon;
    pl.baseSpd = st.spd;
    pl.baseAtk = st.atk;
    if (prev) { pl.maxHp = Math.max(1, pl.maxHp + st.hp - prev.hp); pl.dmgReduce = Math.max(0, pl.dmgReduce - prev.taken + st.taken); }
    else { pl.maxHp = Math.max(1, pl.maxHp - (hp0 != null ? hp0 : G.DEX_BY[d].hp) + st.hp); pl.hp = pl.maxHp; pl.dmgReduce += st.taken; }
    pl.hp = Math.min(pl.hp, pl.maxHp);
    for (const m of pl.moves) scaleMove(m, st);
    S.st = st;
    return st;
  }
  /** A move instance's damage at its class's multiplier (m.xk, so a later stage can rescale it). */
  function scaleMove(m, st) {
    if (m.dmg == null) return;
    const k = factorOf(m.id, st), k0 = m.xk || 1;
    if (Math.abs(k - k0) > 1e-9) m.dmg = m.dmg * k / k0;
    m.xk = k;
  }
  function learnKit(pl, i) {
    const m = BY[S.member], id = m.kit[i];
    if (!id || pl.hasMove(id)) return false;
    if (!pl.addMove(id)) return false;
    scaleMove(pl.moves.find(x => x.id === id), S.st);
    S.kit = Math.max(S.kit, i + 1);
    return true;
  }

  /** An Expedition run starts (js/expedition/core.js run.start): the League member's stage 1, its kit's first move, passive. */
  function begin(pl, cfg) {
    S = null;
    if (!pl || !G.Modes.isExp()) return null;
    const d = BY[cfg && cfg.dex] ? cfg.dex : FAM[pl.dex] && BY[FAM[pl.dex]] ? FAM[pl.dex] : K.DEFAULT;
    const m = BY[d];
    S = { member: d, form: d, kit: 0, mat: 0, evo: 0, done: 1, pending: null, note: [], st: null, role: m.role,
          ability: G.Abilities.of(finalsOf(m)[0]), log: [] };
    const hp0 = pl.mon.hp;   // (the base stat the player was built with: its bonuses are kept)
    if (pl.dex !== d) body(pl, d);
    applyStats(pl, d, null, hp0);
    // the role (a small stat mod) and the ability (one of the 54), the member's for the whole run
    const r = K.ROLE[m.role] || {};
    if (r.regen) pl.regenFlat += r.regen;
    if (r.atk) pl.atkMul *= 1 + r.atk;
    if (r.taken) pl.dmgReduce += r.taken;
    if (r.spd) pl.spdMul *= 1 + r.spd;
    G.Abilities.set(pl, S.ability);
    // the kit owns the move slots: its first move only (no start move, no "Repertoire" second move)
    G.Projectiles.clearOrbs(pl);
    pl.moves = []; pl.slots = []; pl.active = 0;
    pl.xkit = true;
    learnKit(pl, 0);
    pl.setActive(0);
    return S;
  }
  function reset() { S = null; }

  /** Every level the player reached since the last check: kit moves, an evolution (or a branch to choose), Maturity. */
  function process(pl) {
    if (!on(pl) || S.pending) return;
    const m = BY[S.member];
    while (S.done < pl.level && !S.pending) {
      const lv = S.done + 1;
      const ki = K.KIT_AT.indexOf(lv);
      if (ki > 0 && learnKit(pl, ki)) { const id = m.kit[ki]; S.note.push(T.f('Movimiento del kit: {x} ({x}/4)', T.t(G.Moves.BY_ID[id].name), ki + 1)); S.log.push([lv, 'kit', id]); }
      const nx = nextOf(m, S.form), at = evoLevel(m, S.form);
      if (nx.length && lv >= at) {
        if (nx.length === 1) evolve(pl, nx[0][0], lv);
        else { S.pending = { lv, opts: nx.map(x => x[0]) }; S.done = lv; S.log.push([lv, 'branch', S.pending.opts.slice()]); return; }
      }
      if (!nextOf(m, S.form).length && K.MATURE_AT.includes(lv)) mature(pl, lv);
      S.done = lv;
    }
  }
  /** Evolve into species `to` (a level-up): its sprite, types and stats; HP back up. */
  function evolve(pl, to, lv) {
    if (!S || !G.DEX_BY[to] || FAM[to] !== S.member) return false;
    const from = S.form, prev = S.st || statsOf(from);
    body(pl, to);
    applyStats(pl, to, prev);
    G.Abilities.set(pl, S.ability);
    pl.hp = Math.min(pl.maxHp, Math.max(pl.hp, pl.maxHp * K.EVO_FLOOR) + pl.maxHp * K.EVO_HEAL);
    S.form = to; S.evo++; S.pending = null;
    S.log.push([lv || pl.level, 'evo', to]);
    const txt = T.f('¡{x} evoluciona a {x}!', name(from), name(to));
    S.note.push(txt);
    G.Spawner.say(txt, 3, true);
    G.Game.flash('#ffffff', 0.6);
    G.FX.ring(pl.x, pl.y, 8, 150, '#ffffff', 0.8, 6);
    G.FX.burst(pl.x, pl.y - pl.bodyH * 0.5, '#fff6c8', 46, 260);
    G.Audio.sfx('legend');
    return true;
  }
  function mature(pl, lv) {
    S.mat++;
    pl.atkMul *= 1 + K.MATURE_K;
    pl.addMaxHp(Math.round(pl.maxHp * K.MATURE_K));
    S.log.push([lv, 'mat', S.mat]);
    const txt = T.f('¡{x} alcanza la madurez {x}!', name(S.form), S.mat);
    S.note.push(txt);
    G.Spawner.say(txt, 3, true);
    G.FX.ring(pl.x, pl.y, 8, 130, '#ffd23f', 0.8, 6);
    G.Audio.sfx('legend');
  }
  /** The branch cards (the level-up's cards while a choice waits): one per form, its sprite on it. */
  function branchCards(pl) {
    const from = S.form, prev = S.st || statsOf(from);
    return S.pending.opts.map(to => {
      const st = statsOf(to), p = G.DEX_BY[to];
      return {
        w: 0, type: 'xevo', key: 'xevo:' + to, sprite: to, icon: 'star', color: '#ffd23f', tag: T.t('EVOLUCIÓN'),
        title: name(from) + ' → ' + name(to),
        desc: T.f('{x} · Vida {x} → {x}', p.types.map(t => T.t(G.U.TYPE_NAME[t])).join(' / '), Math.round(pl.maxHp), Math.round(pl.maxHp + st.hp - prev.hp)),
        apply: q => { evolve(q, to, S.pending ? S.pending.lv : q.level); process(q); }
      };
    });
  }
  /** The levelup.offer seam (js/systems/levelup.js, before the cards are drawn): an Expedition League run's levels; a
   *  branch waiting -> its cards instead of the base ones. Base runs / other players: undefined (the base cards). */
  function offerHook(pl) {
    if (!on(pl)) return undefined;
    process(pl);
    if (S.pending) { const c = branchCards(pl); c.note = [T.f('¿En qué evoluciona {x}?', name(S.form))].concat(S.note); wrap(c); return c; }
    return undefined;
  }
  /** The levelup.cards seam: the base cards of an Expedition League run get the level's news (kit move, evolution). */
  function cardsHook(cards, pl) {
    if (!on(pl) || !S.note.length) return cards;
    cards.note = S.note.slice();
    wrap(cards);
    return cards;
  }
  function wrap(cards) { for (const c of cards) { if (c.xw) continue; const a = c.apply; c.xw = true; c.apply = p => { S && (S.note = []); return a(p); }; } }

  // ---------------- the `x` block's `l` (viewers and guests) ----------------
  /** The League row of the local player: [member, form, kit moves, Maturity, evolutions] (null outside a League run). */
  const row = () => S ? [S.member, S.form, S.kit, S.mat, S.evo] : null;
  /** A viewer's / host's puppet p shows row r's form (only the sprite: a puppet has no stats of its own). */
  function applyRow(p, r) {
    if (!p) return false;
    p.xlg = Array.isArray(r) ? r : null;
    const to = p.xlg && p.xlg[1] | 0;
    if (!to || !G.DEX_BY[to] || p.dex === to) return false;
    p.mon = G.DEX_BY[to];
    body(p, to);
    return true;
  }

  // ---------------- the end of the run ----------------
  /** The run into the Expedition save (js/expedition/core.js run.end): counters for the challenges, then new members. */
  function record(sum) {
    const Svv = Sv();
    if (!S) return [];
    const m = BY[S.member], types = new Set(G.DEX_BY[S.member].types.concat(G.DEX_BY[S.form].types));
    Svv.bump('kos', sum.kills || 0);
    for (const t of types) Svv.bump('ko.t.' + t, sum.kills || 0);
    const run = G.ExpClassic && G.ExpClassic.run;
    const guards = run ? run.bosses.filter(b => b.zone <= 3 && b.down != null).length : 0;
    if (guards) Svv.bump('guardians', guards);
    if (S.evo) Svv.bump('lg.evo', S.evo);
    Svv.best('lg.mat', S.mat);
    Svv.best('lg.lv', sum.level || 1);
    Svv.bump('lg.runs.' + m.dex);
    Svv.best('lg.best.' + m.dex, sum.level || 1);
    Svv.add('league.played', m.dex);
    return checkChallenges();
  }
  /** The run-over screen's League lines (before record: the new members come from record's return). */
  function lines(newly) {
    if (!S) return [];
    const out = [T.f('Liga: {x}', name(S.member) + (S.form !== S.member ? ' → ' + name(S.form) : '') + (S.mat ? ' · ' + T.f('madurez {x}', S.mat) : ''))];
    for (const d of newly || []) out.push(T.f('¡Nuevo miembro de la Liga: {x}!', name(d)));
    return out;
  }

  // ---------------- the League screen ("Choose your League member", js/ui/modes-ui.js) ----------------
  let sel = 0;
  const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  /** The roster grid + the selected member's card, into box (#modes-league). onPick(dex) when a playable one is chosen;
   *  onBack() for its "Back" button. */
  function renderPicker(box, onPick, onBack) {
    const list = ids(), have = roster();
    if (!BY[sel]) sel = pickFor();
    const m = BY[sel], st = statsOf(m.dex), b = D.base[m.dex], pr = progress(m.ch), ok = playable(m.dex);
    const evoTxt = stagesOf(m).filter(d => m.evo[d]).map(d => name(d) + ' → ' + m.evo[d].map(([to, lv]) => name(to) + ' (' + T.f('Nv. {x}', lv) + ')').join(' / ')).join(' · ');
    const kit = m.kit.map((id, i) => `<li><span class="lg-lv">${T.f('Nv. {x}', K.KIT_AT[i])}</span> ${G.Icons.html('move:' + id, 18)} <span>${esc(T.t(G.Moves.BY_ID[id].name))}</span></li>`).join('');
    const ch = !m.ch ? `<span class="lg-free">${T.t('Gratis')}</span>`
      : pr.parts.map(p => `<div class="lg-ch${p.have >= p.need ? ' done' : ''}"><span>${esc(p.text)}</span> <b>${p.have} / ${p.need}</b></div>`).join('')
        + (pr.done ? `<div class="lg-ok">${T.t('Cumplido: ya puedes jugarlo')}</div>` : '');
    box.innerHTML = `
      <div class="row between lg-head"><h3 id="league-count">${esc(T.f('Liga: {x} / {x} disponibles', have.length, list.length))}</h3><button id="league-back" class="btn small">${T.t('Atrás')}</button></div>
      <div class="lg-wrap">
        <div class="lg-card" id="league-detail" data-dex="${m.dex}">
          <div class="lg-top"><span class="lg-spr"></span><div><b class="lg-name">${esc(name(m.dex))}</b>
            <span class="lg-rank" style="background:${RANK_COL[m.rank]}">${T.t(RANK_NAME[m.rank])}</span>
            <div class="lg-role">${T.t(ROLE_NAME[m.role])} · <span>${T.t(ROLE_DESC[m.role])}</span></div></div></div>
          ${G.UI.abilityLine(finalsOf(m)[0], true, G.Abilities.of(finalsOf(m)[0]))}
          <div class="lg-sec">${T.t('Kit')}</div><ul class="lg-kit">${kit}</ul>
          <div class="lg-sec">${T.t('Evolución')}</div><div class="lg-evo">${esc(evoTxt || T.t('No evoluciona: madura a Nv. 24 y 44'))}</div>
          <div class="lg-mat">${T.t('Madura a Nv. 24 y 44 cuando ya no evoluciona (+12 % de daño y vida)')}</div>
          <div class="lg-stats">${esc(T.f('Vida {x} · Ataque {x} · Defensa {x} · At. Esp. {x} · Def. Esp. {x} · Velocidad {x}', ...b))}</div>
          <div class="lg-sec">${T.t('Reto')}</div>${ch}
          ${ok ? `<button class="btn lg-go" id="league-go">${G.Icons.html('ball', 18)} ${T.t('Empieza con él')}</button>` : ''}
        </div>
        <div class="grid party-grid lg-grid" id="league-grid"></div>
      </div>`;
    box.querySelector('.lg-spr').appendChild(G.UI.spriteCanvas(m.dex, 72, 64, { scale: 2, shadow: ok, silhouette: !ok }));
    const grid = box.querySelector('#league-grid'), cur = pickFor();
    for (const d of list) {
      const M = BY[d], can = playable(d), cell = document.createElement('div');
      cell.className = 'cell' + (d === sel ? ' on' : '') + (can ? '' : ' locked');
      cell.dataset.dex = d;
      cell.insertAdjacentHTML('beforeend', `<span class="no">${String(d).padStart(3, '0')}</span>` + (d === cur ? `<span class="badge-r">${G.Icons.html('crown', 14)}</span>` : ''));
      cell.appendChild(G.UI.spriteCanvas(d, 80, 64, { scale: 2, shadow: can, silhouette: !can }));
      cell.insertAdjacentHTML('beforeend', `<b>${esc(name(d))}</b><small class="lg-cr" style="color:${RANK_COL[M.rank]}">${T.t(can ? (M.ch ? '¡Disponible!' : RANK_NAME[M.rank]) : RANK_NAME[M.rank])}</small>`);
      cell.onclick = () => {
        // one tap shows it; a tap on the shown one (or "Start with it") picks it
        if (sel === d && can) { choose(d); return; }
        sel = d; G.Audio.sfx('select'); renderPicker(box, onPick, onBack);
      };
      grid.appendChild(cell);
    }
    const later = document.createElement('div');
    later.className = 'lg-later';
    const n = { D4b: 0, D4c: 0, D4d: 0 };
    for (const s of D.stubs) n[s.batch]++;
    later.innerHTML = `<b>${T.t('Más miembros de la Liga')}</b> ` + Object.entries(n).map(([k, v]) => `<span>${esc(T.f('Llegará con la tanda {x}', k))}: ${v}</span>`).join(' · ');
    grid.appendChild(later);
    box.querySelector('#league-back').onclick = () => { if (onBack) onBack(); };
    const go = box.querySelector('#league-go');
    if (go) go.onclick = () => choose(m.dex);
    function choose(d) { if (!setPick(d)) { G.Audio.sfx('error'); return; } G.Audio.sfx('confirm'); if (onPick) onPick(d); }
    // keep the selected cell in view (a long roster on a phone): the grid scrolls, never the screen round it
    const on0 = grid.querySelector('.cell.on');
    if (on0) { const top = on0.offsetTop - grid.offsetTop; if (top < grid.scrollTop || top + on0.offsetHeight > grid.scrollTop + grid.clientHeight) grid.scrollTop = Math.max(0, top - 8); }
    return box;
  }
  function select(d) { if (BY[d]) sel = d; return sel; }

  return {
    K, D, BY, FAM, PHYS, STATUS, stagesOf, finalsOf, nextOf, evoLevel, statsOf, classOf, factorOf,
    free, own, met, playable, roster, progress, checkChallenges, counter, chText, readPick, setPick, pickFor,
    begin, reset, process, evolve, offerHook, cardsHook, row, applyRow, record, lines, renderPicker, select,
    get run() { return S; }, get on() { return !!S && G.Modes.isExp(); }
  };
})();

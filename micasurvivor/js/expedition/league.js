  function record(sum) {
    const Svv = Sv();
    if (!S) return [];
    const m = BY[S.member], types = new Set(G.DEX_BY[S.member].types.concat(G.DEX_BY[S.form].types));
    Svv.bump('kos', sum.kills || 0);
    for (const t of types) Svv.bump('ko.t.' + t, sum.kills || 0);
    const run = G.ExpClassic && G.ExpClassic.run;
    const guards = run ? run.bosses.filter(b => b.zone <= 3 && b.down != null).length : 0;
    if (guards) Svv.bump('guardians', guards);
    if (S.evo) Svv.bump('lg.evo', S.evo);
    Svv.best('lg.mat', S.mat);
    Svv.best('lg.lv', sum.level || 1);
    Svv.bump('lg.runs.' + m.dex);
    Svv.best('lg.best.' + m.dex, sum.level || 1);
    Svv.add('league.played', m.dex);
    if (S.mega) { Svv.bump('lg.mega'); Svv.add('mega.seen', S.mega); }   // (D14)
    return checkChallenges();
  }
